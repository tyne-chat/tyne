// Fork: tests of scripts/fork-string-lint.mjs, the check for hard-coded user-facing strings in the
// fork's code (tyne-chat/tyne#184).

import {describe, expect, it} from 'vitest';
import {lintSource} from '../../../scripts/fork-string-lint.mjs';

const lint = (source: string, lines: 'all' | Set<number> = 'all'): Array<string> =>
	lintSource('src/Example.tsx', source, lines);

describe('fork-string-lint', () => {
	it('reports literals where people read them', () => {
		const problems = lint(
			[
				"Toast.error('Failed to update persona mode');",
				"ToastCommands.createToast({type: 'error', children: 'Persona name cannot be empty'});",
				'const a = <span>Alice</span>;',
				'const b = <input placeholder="e.g. Wonderland" />;',
				'const c = <svg aria-label="Powered by KLIPY" />;',
				`const tooltipText = \`Account: @\${name}\`;`,
				"createSystemMessage(channelId, 'Persona deselected.');",
				"const d = <span title={busy ? 'Saving now' : label} />;",
			].join('\n'),
		);
		expect(problems).toEqual([
			'src/Example.tsx:1:13: Toast.error(): "Failed to update persona mode"',
			'src/Example.tsx:2:53: key children: "Persona name cannot be empty"',
			'src/Example.tsx:3:17: JSX text: "Alice"',
			'src/Example.tsx:4:30: prop placeholder: "e.g. Wonderland"',
			'src/Example.tsx:5:27: prop aria-label: "Powered by KLIPY"',
			'src/Example.tsx:6:21: variable tooltipText: "Account: @"',
			'src/Example.tsx:7:32: createSystemMessage(): "Persona deselected."',
			'src/Example.tsx:8:31: prop title: "Saving now"',
		]);
	});

	it('reports an expression inside <Trans>, which is inserted untranslated', () => {
		expect(lint("const a = <Trans>{done} of {total} {label ?? 'items'}</Trans>;")).toEqual([
			'src/Example.tsx:1:46: JSX child: "items"',
		]);
	});

	it('leaves translated strings alone', () => {
		expect(
			lint(
				[
					'const A = msg`Failed to save persona`;',
					"const B = msg({message: 'Persona updated', comment: 'Toast when a persona is updated'});",
					'const c = <Trans>Tag Icon</Trans>;',
					"const d = <Trans>{'Tag Icon'}</Trans>;",
					'Toast.error(i18n._(FAILED_DESCRIPTOR));',
				].join('\n'),
			),
		).toEqual([]);
	});

	it('leaves strings nobody reads alone', () => {
		expect(
			lint(
				[
					"console.log('Persona list loaded');",
					"logger.warn('Failed to load personas');",
					"throw new Error('Persona list is not loaded');",
					'const a = <div className="row wide" data-flx="persona.row" />;',
					"PersonaEditModal.displayName = 'PersonaEditModal';",
					"const b = {type: 'error', debugMessage: 'Already pending, ignoring request'};",
					"const c = mode === 'Manual mode' ? 1 : 2;",
					"const d = {label: 'persona-row'};",
				].join('\n'),
			),
		).toEqual([]);
	});

	it('skips a literal marked i18n-ignore, with a reason', () => {
		expect(
			lint(
				[
					'// i18n-ignore: KLIPY asks for its mark in English',
					"Toast.error('Powered by KLIPY');",
					"Toast.error('Network error'); // i18n-ignore: shown to developers only",
					'// i18n-ignore:',
					"Toast.error('Active persona cleared');",
				].join('\n'),
			),
		).toEqual(['src/Example.tsx:5:13: Toast.error(): "Active persona cleared"']);
	});

	it('lets an i18n-ignore comment above a wrapped statement cover its literal', () => {
		expect(
			lint(
				[
					'// i18n-ignore: a process name, not text in the app',
					'const playerTitle =',
					"\t'Example GIF preview';",
					'const otherTitle =',
					"\t'Example GIF preview';",
				].join('\n'),
			),
		).toEqual(['src/Example.tsx:5:2: variable otherTitle: "Example GIF preview"']);
	});

	it('does not let an i18n-ignore comment above a long statement cover all of it', () => {
		expect(
			lint(
				[
					'// i18n-ignore: the first title is a process name',
					'const view = (',
					'\t<div>',
					'\t\t<span title="Example GIF preview" />',
					'\t\t<br />',
					'\t\t<br />',
					'\t\t<span>Persona deselected.</span>',
					'\t</div>',
					');',
				].join('\n'),
			),
		).toEqual([
			'src/Example.tsx:4:15: prop title: "Example GIF preview"',
			'src/Example.tsx:7:9: JSX text: "Persona deselected."',
		]);
	});

	it('checks only the lines it is given', () => {
		const source = [
			"Toast.error('Failed to set active persona');",
			"Toast.error('Failed to clear active persona');",
		].join('\n');
		expect(lint(source, new Set([2]))).toEqual([
			'src/Example.tsx:2:13: Toast.error(): "Failed to clear active persona"',
		]);
	});

	it('skips generated files', () => {
		expect(
			lint(
				"// SPDX-License-Identifier: AGPL-3.0-or-later\n// Generated by scripts/Example.ts.\nToast.error('Failed to save');",
			),
		).toEqual([]);
	});
});
