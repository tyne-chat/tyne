// Fork: AST and source safety checks for backend (fluxer_api, packages/schema), desktop
// (fluxer_desktop), Rust services, and Gleam gateway tests (tyne-chat/tyne#947).
//
//   node scripts/fork-backend-desktop-lint.mjs [--upstream <git ref>] [--all] [--rule <r1,r2>] [<file>...]
//
// Rules:
// 1. `non-atomic-index-write`: separate awaits writing a base table and its `*By*` index table
//    (or sibling `*By*` index tables) without `BatchBuilder` or `executeGroupedBatches`.
// 2. `zod-schema-trap`: `z.coerce.number()` in `*Query*Schema`, `.register(schemaMetadata,
//    {preserveEmptyValues: true})` before `.default()`, or `.default()` in Update/Patch schemas
//    (`tyne-chat/tyne#200`).
// 3. `promise-race-timeout-leak`: `Promise.race` paired with `setTimeout` without `clearTimeout`
//    or `.unref()` in the same function/method.
// 4. `desktop-ipc-sender`: mutating/sensitive `ipcMain.handle`/`ipcMain.on` handlers missing
//    sender validation.
// 5. `desktop-window-safety`: post-`await` BrowserWindow/webContents calls without `isDestroyed()`,
//    `dialog.showMessageBox` in update paths (`tyne-chat/tyne#299`), or `getMainWindow()?.webContents.send`
//    broadcasts that skip extra windows (`tyne-chat/tyne#331`).
// 6. `api-controller-hygiene`: shadowed Hono routes, `OpenAPI()` missing `responseSchema`, `@me`
//    OAuth scopes without `requireOAuth2Scope`, `VIEW_CHANNEL` throwing 403 instead of 404,
//    and `vi.mock()` in non-isolated `fluxer_api` test files (`tyne-chat/tyne#126`).
// 7. `rust-async-blocking-fs`: `std::fs::` inside `async fn` in non-test Rust crates.
// 8. `gleam-fork-test-sleep`: `process.sleep(` directly inside fork Gleam `*_test()` functions.
//
// Suppress a deliberate exception with `// safety-lint-ignore: <reason>` on its line or the line above.

