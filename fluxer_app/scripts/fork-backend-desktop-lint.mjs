function git(...args) {
	return execFileSync('git', args, {cwd: REPO_ROOT, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	const scopes = ['fluxer_api/src', 'packages/schema/src/domains', 'fluxer_desktop/src', 'fluxer_gateway'];
	for (const line of git(
		'diff',
		'-U0',
		'--no-color',
		'--no-renames',
		'--diff-filter=AM',
		base,
		'--',
		...scopes,
		'*.rs',
	).split('\n')) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', ...scopes, '*.rs').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

function isLineEnabled(lines, line) {
	return Boolean(line && (lines === 'all' || lines.has(line)));
}

function collectIgnoredLines(comments, source) {
	const ignored = new Set();
	if (comments) {
		for (const comment of comments) {
			if (IGNORE_RE.test(comment.value)) {
				ignored.add(comment.loc.end.line);
				ignored.add(comment.loc.end.line + 1);
			}
		}
	} else {
		const rawLines = source.split('\n');
		for (let i = 0; i < rawLines.length; i++) {
			if (IGNORE_RE.test(rawLines[i])) {
				ignored.add(i + 1);
				ignored.add(i + 2);
			}
		}
	}
	return ignored;
}

function walkAst(node, visit, ancestors = []) {
	if (!node || typeof node.type !== 'string') return;
	visit(node, ancestors);
	ancestors.push(node);
	for (const key of Object.keys(node)) {
		if (key === 'loc' || key.endsWith('Comments')) continue;
		const val = node[key];
		if (Array.isArray(val)) {
			for (const child of val) walkAst(child, visit, ancestors);
		} else if (val && typeof val === 'object' && typeof val.type === 'string') {
			walkAst(val, visit, ancestors);
		}
	}
	ancestors.pop();
}

function areSiblingIndexTables(tables) {
	if (tables.length < 2) return false;
	for (let i = 0; i < tables.length; i++) {
		for (let j = i + 1; j < tables.length; j++) {
			const a = tables[i];
			const b = tables[j];
			if (a === b) continue;
			const aRoot = a.split('By')[0];
			const bRoot = b.split('By')[0];
			if (
				aRoot === bRoot ||
				aRoot.replace(/s$/, '') === bRoot.replace(/s$/, '') ||
				b.startsWith(`${a}By`) ||
				a.startsWith(`${b}By`)
			) {
				return true;
			}
		}
	}
	return false;
}

function checkNonAtomicIndexWrite(source, ast, lines, ignored, report) {
	walkAst(ast.program, (node, ancestors) => {
		const isFn =
			node.type === 'ClassMethod' ||
			node.type === 'FunctionDeclaration' ||
			node.type === 'FunctionExpression' ||
			node.type === 'ArrowFunctionExpression';
		if (!isFn || !node.async || !node.body) return;
		const bSrc = source.slice(node.body.start, node.body.end);
		if (bSrc.includes('BatchBuilder') || bSrc.includes('executeGroupedBatches')) return;
		const enclosing = enclosingAstSymbol([...ancestors, node]);

		// Only inspect direct awaits in this function (ignore inner nested functions).
		const writes = [];
		const innerAncestors = [];
		const scanBody = (n) => {
			if (!n || typeof n.type !== 'string') return;
			if (
				n !== node &&
				(n.type === 'FunctionDeclaration' ||
					n.type === 'FunctionExpression' ||
					n.type === 'ArrowFunctionExpression' ||
					n.type === 'ClassMethod')
			) {
				return;
			}
			if (n.type === 'AwaitExpression' && n.argument?.type === 'CallExpression') {
				const call = n.argument;
				const fnName = call.callee.type === 'Identifier' ? call.callee.name : undefined;
				if (fnName === 'upsertOne' || fnName === 'deleteOneOrMany' || fnName === 'executePrepared') {
					const arg = call.arguments[0];
					if (
						arg?.type === 'CallExpression' &&
						arg.callee.type === 'MemberExpression' &&
						arg.callee.object.type === 'Identifier' &&
						arg.callee.property.type === 'Identifier' &&
						/^(upsert|patch|delete)/.test(arg.callee.property.name)
					) {
						writes.push({
							table: arg.callee.object.name,
							line: n.loc?.start.line,
							col: (n.loc?.start.column ?? 0) + 1,
						});
					}
				}
			}
			innerAncestors.push(n);
			for (const k of Object.keys(n)) {
				if (k === 'loc' || k.endsWith('Comments')) continue;
				const v = n[k];
				if (Array.isArray(v)) v.forEach(scanBody);
				else if (v && typeof v === 'object' && typeof v.type === 'string') scanBody(v);
			}
			innerAncestors.pop();
		};
		scanBody(node.body);

		const uniqueTables = [...new Set(writes.map((w) => w.table))];
		if (areSiblingIndexTables(uniqueTables)) {
			const target = writes.find((w) => w.table !== writes[0].table) ?? writes[1];
			if (isLineEnabled(lines, target.line) && !ignored.has(target.line)) {
				report(
					'non-atomic-index-write',
					target.line,
					target.col,
					`separate awaited writes to [${uniqueTables.join(', ')}] without BatchBuilder risk index desync`,
					{enclosing, symbol: uniqueTables.join(',')},
				);
			}
		}
	});
}

function checkZodSchemas(source, ast, lines, ignored, report) {
	for (const stmt of ast.program.body) {
		const decl = stmt.type === 'ExportNamedDeclaration' ? stmt.declaration : stmt;
		if (decl?.type !== 'VariableDeclaration') continue;
		for (const d of decl.declarations) {
			if (d.id?.type !== 'Identifier' || !d.init) continue;
			const schemaName = d.id.name;
			const isQuery = /Query(Schema)?$/i.test(schemaName);
			const isPatch = /(Update|Patch).*RequestSchema$/i.test(schemaName) || /^Patch.*Schema$/i.test(schemaName);
			if (!isQuery && !isPatch) continue;

			walkAst(d.init, (node, ancestors) => {
				const line = node.loc?.start.line;
				const col = (node.loc?.start.column ?? 0) + 1;
				if (!isLineEnabled(lines, line) || ignored.has(line)) return;

				if (
					isQuery &&
					node.type === 'CallExpression' &&
					node.callee.type === 'MemberExpression' &&
					node.callee.property.type === 'Identifier' &&
					node.callee.object.type === 'MemberExpression' &&
					node.callee.object.object.type === 'Identifier' &&
					node.callee.object.object.name === 'z' &&
					node.callee.object.property.type === 'Identifier' &&
					node.callee.object.property.name === 'coerce'
				) {
					if (node.callee.property.name === 'boolean') {
						report(
							'zod-schema-trap',
							line,
							col,
							`\`z.coerce.boolean()\` in \`${schemaName}\` turns \`"false"\` into \`true\` (use \`QueryBooleanType\`)`,
							{enclosing: schemaName, symbol: schemaName, target: 'z.coerce.boolean()'},
						);
					} else if (node.callee.property.name === 'number') {
						const propAnc = [...ancestors].reverse().find((a) => a.type === 'ObjectProperty');
						const propSrc = propAnc ? source.slice(propAnc.start, propAnc.end) : '';
						const hasPositiveMin =
							/\.positive\s*\(\s*\)/.test(propSrc) ||
							[...propSrc.matchAll(/\.min\s*\(\s*([+-]?\d+)/g)].some((m) => Number(m[1]) >= 1);
						if (!hasPositiveMin) {
							report(
								'zod-schema-trap',
								line,
								col,
								`\`z.coerce.number()\` without \`min(>=1)\` in \`${schemaName}\` turns empty \`?k=\` (null) into 0 (use \`createQueryIntegerType\` or positive \`min\`; tyne-chat/tyne#200)`,
								{enclosing: schemaName, symbol: schemaName, target: 'z.coerce.number()'},
							);
						}
					}
				}

				if (
					isQuery &&
					node.type === 'CallExpression' &&
					node.callee.type === 'MemberExpression' &&
					node.callee.property.type === 'Identifier' &&
					node.callee.property.name === 'default'
				) {
					const innerSrc = source.slice(node.callee.object.start, node.callee.object.end);
					if (/\.register\(\s*schemaMetadata\s*,\s*\{[^}]*preserveEmptyValues\s*:\s*true/.test(innerSrc)) {
						report(
							'zod-schema-trap',
							line,
							col,
							`\`preserveEmptyValues: true\` registered before \`.default()\` in \`${schemaName}\` is hidden from Validator.ts (place \`.register()\` after \`.default()\`; tyne-chat/tyne#200)`,
							{enclosing: schemaName, symbol: schemaName, target: 'preserveEmptyValues'},
						);
					}
				}

				if (
					isPatch &&
					node.type === 'CallExpression' &&
					node.callee.type === 'MemberExpression' &&
					node.callee.property.type === 'Identifier' &&
					node.callee.property.name === 'default'
				) {
					report(
						'zod-schema-trap',
						line,
						col,
						`\`.default()\` in Update/Patch schema \`${schemaName}\` overwrites stored values when fields are omitted`,
						{enclosing: schemaName, symbol: schemaName, target: '.default()'},
					);
				}
			});
		}
	}
}

function checkPromiseRaceTimeoutLeak(source, ast, lines, ignored, report) {
	walkAst(ast.program, (node, ancestors) => {
		if (
			node.type === 'CallExpression' &&
			node.callee.type === 'MemberExpression' &&
			node.callee.object.type === 'Identifier' &&
			node.callee.object.name === 'Promise' &&
			node.callee.property.type === 'Identifier' &&
			node.callee.property.name === 'race'
		) {
			const line = node.loc?.start.line;
			const col = (node.loc?.start.column ?? 0) + 1;
			if (!isLineEnabled(lines, line) || ignored.has(line)) return;

			const fnAnc = [...ancestors]
				.reverse()
				.find(
					(a) =>
						a.type === 'FunctionDeclaration' ||
						a.type === 'FunctionExpression' ||
						a.type === 'ArrowFunctionExpression' ||
						a.type === 'ClassMethod',
				);
			const scopeSrc = fnAnc ? source.slice(fnAnc.start, fnAnc.end) : source.slice(node.start, node.end);
			if (
				/\bsetTimeout\s*\(/.test(scopeSrc) &&
				!/\bclearTimeout\s*\(/.test(scopeSrc) &&
				!/\.unref\s*\(/.test(scopeSrc)
			) {
				report(
					'promise-race-timeout-leak',
					line,
					col,
					'`Promise.race` with `setTimeout` without `clearTimeout` leaks a refed timer on early completion',
					{enclosing: enclosingAstSymbol(ancestors), target: 'Promise.race'},
				);
			}
		}
	});
}

function collectSameFileFunctions(ast, source) {
	const fns = new Map();
	for (const stmt of ast.program.body) {
		const decl = stmt.type === 'ExportNamedDeclaration' ? stmt.declaration : stmt;
		if (decl?.type === 'FunctionDeclaration' && decl.id) {
			fns.set(decl.id.name, source.slice(decl.start, decl.end));
		} else if (decl?.type === 'VariableDeclaration') {
			for (const d of decl.declarations) {
				if (
					d.id?.type === 'Identifier' &&
					d.init &&
					(d.init.type === 'ArrowFunctionExpression' || d.init.type === 'FunctionExpression')
				) {
					fns.set(d.id.name, source.slice(d.init.start, d.init.end));
				}
			}
		}
	}
	return fns;
}

function checkDesktopIpcSender(source, ast, lines, ignored, report) {
	const fileFns = collectSameFileFunctions(ast, source);
	walkAst(ast.program, (node, ancestors) => {
		if (
			node.type !== 'CallExpression' ||
			node.callee.type !== 'MemberExpression' ||
			node.callee.object.type !== 'Identifier' ||
			node.callee.object.name !== 'ipcMain' ||
			node.callee.property.type !== 'Identifier' ||
			(node.callee.property.name !== 'handle' && node.callee.property.name !== 'on')
		) {
			return;
		}
		const line = node.loc?.start.line;
		const col = (node.loc?.start.column ?? 0) + 1;
		if (!isLineEnabled(lines, line) || ignored.has(line)) return;

		const channelNode = node.arguments[0];
		const handlerNode = node.arguments[1];
		if (!handlerNode) return;
		if (channelNode?.type === 'StringLiteral' && READONLY_SAFE_IPC_CHANNELS.has(channelNode.value)) return;
		const chLabel = channelNode ? source.slice(channelNode.start, channelNode.end) : '<unknown>';

		let handlerSrc = '';
		if (handlerNode.type === 'Identifier') {
			// Check top-level or nested helper declaration inside source (e.g., onFirstContentPainted in Window.ts)
			handlerSrc = fileFns.get(handlerNode.name) ?? '';
			if (!handlerSrc) {
				walkAst(ast.program, (inner) => {
					if (
						inner.type === 'VariableDeclarator' &&
						inner.id?.type === 'Identifier' &&
						inner.id.name === handlerNode.name &&
						inner.init
					) {
						handlerSrc = source.slice(inner.init.start, inner.init.end);
					}
				});
			}
		} else {
			handlerSrc = source.slice(handlerNode.start, handlerNode.end);
		}
		if (!handlerSrc) return;
		if (IPC_SENDER_GUARD_RE.test(handlerSrc)) return;

		// Follow 1-hop same-file function calls like `helper(event, ...)`
		const calledIdents = [...handlerSrc.matchAll(/\b([A-Za-z_][A-Za-z0-9_]*)\s*\(/g)].map((m) => m[1]);
		if (calledIdents.some((fn) => fileFns.has(fn) && IPC_SENDER_GUARD_RE.test(fileFns.get(fn)))) return;

		report(
			'desktop-ipc-sender',
			line,
			col,
			`\`ipcMain.${node.callee.property.name}(${chLabel})\` lacks renderer sender validation`,
			{enclosing: enclosingAstSymbol(ancestors), target: chLabel},
		);
	});
}

function checkDesktopWindowSafety(file, source, ast, lines, ignored, report) {
	const isUpdateFile = /(Update|ShellSelfUpdate)\.ts$/.test(file);

	walkAst(ast.program, (node, ancestors) => {
		const line = node.loc?.start.line;
		const col = (node.loc?.start.column ?? 0) + 1;

		// 1. dialog.showMessageBox in update files (tyne-chat/tyne#299)
		if (
			isUpdateFile &&
			node.type === 'CallExpression' &&
			node.callee.type === 'MemberExpression' &&
			node.callee.object.type === 'Identifier' &&
			node.callee.object.name === 'dialog' &&
			node.callee.property.type === 'Identifier' &&
			(node.callee.property.name === 'showMessageBox' || node.callee.property.name === 'showMessageBoxSync') &&
			isLineEnabled(lines, line) &&
			!ignored.has(line)
		) {
			report(
				'desktop-window-safety',
				line,
				col,
				`\`dialog.${node.callee.property.name}\` in update path steals focus (use \`askQuietly\`; tyne-chat/tyne#299)`,
				{enclosing: enclosingAstSymbol(ancestors), target: `dialog.${node.callee.property.name}`},
			);
		}

		// 2. Post-await window / webContents calls without isDestroyed() / isAliveWindow() / try-catch
		const isFn =
			node.type === 'FunctionDeclaration' ||
			node.type === 'FunctionExpression' ||
			node.type === 'ArrowFunctionExpression' ||
			node.type === 'ClassMethod';
		if (isFn && node.async && node.body?.type === 'BlockStatement') {
			const fnEnclosing = enclosingAstSymbol([...ancestors, node]);
			let firstAwaitEnd = -1;
			const findTopLevelAwait = (st) => {
				if (firstAwaitEnd !== -1 || !st) return;
				// Rough statement-level await check outside nested functions
				let hasAwait = false;
				walkAst(st, (inner) => {
					if (hasAwait) return;
					if (
						inner !== node &&
						(inner.type === 'ArrowFunctionExpression' ||
							inner.type === 'FunctionExpression' ||
							inner.type === 'FunctionDeclaration')
					) {
						return;
					}
					if (inner.type === 'AwaitExpression') hasAwait = true;
				});
				if (hasAwait) firstAwaitEnd = st.end;
			};

			for (const st of node.body.body) {
				if (firstAwaitEnd !== -1 && st.type !== 'TryStatement') {
					const stSrc = source.slice(st.start, st.end);
					const betweenAwaitAndStmt = source.slice(firstAwaitEnd, st.end);
					if (!/\b(isDestroyed|isAliveWindow)\s*\(/.test(betweenAwaitAndStmt)) {
						// Inspect direct non-nested calls on window/webContents variables
						walkAst(st, (inner, innerAnc) => {
							if (
								innerAnc.some(
									(a) =>
										a !== st &&
										(a.type === 'ArrowFunctionExpression' ||
											a.type === 'FunctionExpression' ||
											a.type === 'TryStatement'),
								)
							) {
								return;
							}
							if (inner.type !== 'CallExpression' || inner.callee.type !== 'MemberExpression') return;
							const callText = source.slice(inner.callee.start, inner.callee.end);
							if (
								/^(win|window|mainWindow|targetWindow|browserWindow|webContents)(\.webContents)?\.(send|loadURL|executeJavaScript|focus|show|close|setBounds|setTitle)$/.test(
									callText,
								)
							) {
								const cLine = inner.loc?.start.line;
								const cCol = (inner.loc?.start.column ?? 0) + 1;
								if (isLineEnabled(lines, cLine) && !ignored.has(cLine)) {
									report(
										'desktop-window-safety',
										cLine,
										cCol,
										`post-await \`${callText}()\` without \`isDestroyed()\` / \`isAliveWindow()\` guard`,
										{enclosing: fnEnclosing, target: callText},
									);
								}
							}
						});
					}
					void stSrc;
				}
				findTopLevelAwait(st);
			}
		}

		// 3. observe* / app.on event callbacks broadcasting solely to getMainWindow()?.webContents.send (tyne-chat/tyne#331)
		if (
			node.type === 'CallExpression' &&
			node.callee.type === 'MemberExpression' &&
			node.callee.object.type === 'Identifier' &&
			node.callee.object.name === 'app' &&
			node.callee.property.type === 'Identifier' &&
			node.callee.property.name === 'on'
		) {
			const cb = node.arguments[1];
			if (cb) {
				const cbSrc = source.slice(cb.start, cb.end);
				if (
					cbSrc.includes('getMainWindow()') &&
					/\.webContents\.send\(/.test(cbSrc) &&
					!cbSrc.includes('getAppWindows')
				) {
					const cbLine = node.loc?.start.line;
					const cbCol = (node.loc?.start.column ?? 0) + 1;
					if (isLineEnabled(lines, cbLine) && !ignored.has(cbLine)) {
						report(
							'desktop-window-safety',
							cbLine,
							cbCol,
							'`app.on` broadcast targets only `getMainWindow()` and skips extra windows (tyne-chat/tyne#331)',
							{enclosing: enclosingAstSymbol(ancestors), target: 'app.on'},
						);
					}
				}
			}
		}
		if (node.type === 'CallExpression' && node.callee.type === 'Identifier' && /^observe[A-Z]/.test(node.callee.name)) {
			const cb = node.arguments[0];
			if (cb) {
				const cbSrc = source.slice(cb.start, cb.end);
				if (
					cbSrc.includes('getMainWindow()') &&
					/\.webContents\.send\(/.test(cbSrc) &&
					!cbSrc.includes('getAppWindows')
				) {
					const cbLine = node.loc?.start.line;
					const cbCol = (node.loc?.start.column ?? 0) + 1;
					if (isLineEnabled(lines, cbLine) && !ignored.has(cbLine)) {
						report(
							'desktop-window-safety',
							cbLine,
							cbCol,
							`\`${node.callee.name}\` broadcast targets only \`getMainWindow()\` and skips extra windows (tyne-chat/tyne#331)`,
							{enclosing: enclosingAstSymbol(ancestors), target: node.callee.name},
						);
					}
				}
			}
		}
	});
}

function checkApiControllerHygiene(file, source, ast, lines, ignored, report) {
	if (TEST_FILE_RE.test(file)) {
		if (!ISOLATED_API_TEST_FILES.has(file)) {
			walkAst(ast.program, (node, ancestors) => {
				if (
					node.type === 'CallExpression' &&
					node.callee.type === 'MemberExpression' &&
					node.callee.object.type === 'Identifier' &&
					node.callee.object.name === 'vi' &&
					node.callee.property.type === 'Identifier' &&
					(node.callee.property.name === 'mock' || node.callee.property.name === 'doMock')
				) {
					const line = node.loc?.start.line;
					const col = (node.loc?.start.column ?? 0) + 1;
					const prevLine = line ? (source.split('\n')[line - 2] ?? '') : '';
					if (isLineEnabled(lines, line) && !ignored.has(line) && !/\/\/\s*Fork:/.test(prevLine)) {
						report(
							'api-controller-hygiene',
							line,
							col,
							`\`vi.${node.callee.property.name}()\` in non-isolated \`fluxer_api\` test leaks across shared module registry (use \`vi.spyOn\`; tyne-chat/tyne#126)`,
							{enclosing: enclosingAstSymbol(ancestors), target: `vi.${node.callee.property.name}()`},
						);
					}
				}
			});
		}
		return;
	}

	// Non-test fluxer_api checks
	if (file.endsWith('Controller.ts')) {
		const seenRoutes = [];
		walkAst(ast.program, (node, ancestors) => {
			if (
				node.type === 'CallExpression' &&
				node.callee.type === 'MemberExpression' &&
				node.callee.property.type === 'Identifier'
			) {
				const method = node.callee.property.name;
				if (['get', 'post', 'put', 'patch', 'delete'].includes(method) && node.arguments[0]?.type === 'StringLiteral') {
					const line = node.loc?.start.line;
					const col = (node.loc?.start.column ?? 0) + 1;
					const routePath = node.arguments[0].value;
					const segs = routePath.split('/').filter(Boolean);
					const callSrc = source.slice(node.start, node.end);
					const routeTarget = `${method.toUpperCase()} "${routePath}"`;
					const enclosing = enclosingAstSymbol(ancestors);

					if (isLineEnabled(lines, line) && !ignored.has(line)) {
						for (const prev of seenRoutes) {
							if (prev.method !== method || prev.segs.length !== segs.length) continue;
							let shadowed = false;
							let samePrefix = true;
							for (let i = 0; i < segs.length; i++) {
								if (prev.segs[i] === segs[i]) continue;
								if (prev.segs[i].startsWith(':') && !segs[i].startsWith(':')) {
									shadowed = true;
								} else if (!prev.segs[i].startsWith(':') && !segs[i].startsWith(':')) {
									samePrefix = false;
									break;
								}
							}
							if (samePrefix && shadowed) {
								report(
									'api-controller-hygiene',
									line,
									col,
									`${method.toUpperCase()} "${routePath}" is shadowed by earlier "${prev.raw}" at line ${prev.line}`,
									{enclosing, target: routeTarget},
								);
								break;
							}
						}

						if (
							callSrc.includes('OpenAPI(') &&
							!callSrc.includes('responseSchema') &&
							!callSrc.includes('rawResponse')
						) {
							report(
								'api-controller-hygiene',
								line,
								col,
								`${method.toUpperCase()} "${routePath}" has \`OpenAPI()\` without \`responseSchema\` (dropped from openapi.json)`,
								{enclosing, target: routeTarget},
							);
						}

						if (
							/scopes\s*:\s*\[[^\]]+\]/.test(callSrc) &&
							routePath.includes('@me') &&
							!callSrc.includes('requireOAuth2Scope') &&
							!source.includes('requireOAuth2Scope')
						) {
							report(
								'api-controller-hygiene',
								line,
								col,
								`${method.toUpperCase()} "${routePath}" declares OpenAPI scopes without \`requireOAuth2ScopeForBearer\``,
								{enclosing, target: routeTarget},
							);
						}
					}

					seenRoutes.push({method, segs, raw: routePath, line});
				}
			}
		});
	}

	if (source.includes('Permissions.VIEW_CHANNEL')) {
		walkAst(ast.program, (node, ancestors) => {
			if (node.type === 'IfStatement') {
				const line = node.loc?.start.line;
				const col = (node.loc?.start.column ?? 0) + 1;
				const ifSrc = source.slice(node.start, node.end);
				if (
					ifSrc.includes('Permissions.VIEW_CHANNEL') &&
					ifSrc.includes('MissingPermissionsError') &&
					isLineEnabled(lines, line) &&
					!ignored.has(line)
				) {
					report(
						'api-controller-hygiene',
						line,
						col,
						'`Permissions.VIEW_CHANNEL` failure throws `MissingPermissionsError` (403) instead of `UnknownChannelError` (404)',
						{enclosing: enclosingAstSymbol(ancestors), target: 'Permissions.VIEW_CHANNEL'},
					);
				}
			}
		});
	}
}

function maskRustCode(source) {
	// Strip everything from `#[cfg(test)]` onward and blank comments/strings preserving line numbers.
	const testCut = source.search(/#\[\s*cfg\s*\(\s*test\s*\)\s*\]/);
	const prod = testCut === -1 ? source : source.slice(0, testCut);
	const chars = prod.split('');
	let i = 0;
	while (i < chars.length) {
		const c = chars[i];
		const next = chars[i + 1];
		if (c === '/' && next === '/') {
			while (i < chars.length && chars[i] !== '\n') chars[i++] = ' ';
		} else if (c === '/' && next === '*') {
			chars[i++] = ' ';
			chars[i++] = ' ';
			let depth = 1;
			while (i < chars.length && depth > 0) {
				if (chars[i] === '/' && chars[i + 1] === '*') {
					chars[i++] = ' ';
					chars[i++] = ' ';
					depth++;
				} else if (chars[i] === '*' && chars[i + 1] === '/') {
					chars[i++] = ' ';
					chars[i++] = ' ';
					depth--;
				} else {
					if (chars[i] !== '\n') chars[i] = ' ';
					i++;
				}
			}
		} else if (c === '"') {
			chars[i++] = ' ';
			while (i < chars.length && chars[i] !== '"') {
				if (chars[i] === '\\' && i + 1 < chars.length) {
					if (chars[i + 1] !== '\n') chars[i + 1] = ' ';
					chars[i++] = ' ';
				}
				if (chars[i] !== '\n') chars[i] = ' ';
				i++;
			}
			if (i < chars.length) chars[i++] = ' ';
		} else {
			i++;
		}
	}
	return chars.join('');
}

function checkRustAsyncBlockingFs(file, source, lines, ignored, report) {
	if (/(\/tests\/|\/benches\/|tests\.rs$|_test\.rs$|_tests\.rs$|\/examples\/|\/build\.rs$|^tools\/)/.test(file)) {
		return;
	}
	const masked = maskRustCode(source);
	const asyncFnRe = /\basync\s+fn\s+([A-Za-z_][A-Za-z0-9_]*)\b/g;
	for (const m of masked.matchAll(asyncFnRe)) {
		const fnName = m[1];
		// Scan forward until `{` (hitting `;` first means trait signature, not body).
		let idx = m.index + m[0].length;
		let bodyStart = -1;
		while (idx < masked.length) {
			if (masked[idx] === ';') break;
			if (masked[idx] === '{') {
				bodyStart = idx;
				break;
			}
			idx++;
		}
		if (bodyStart === -1) continue;
		let depth = 1;
		let p = bodyStart + 1;
		while (p < masked.length && depth > 0) {
			if (masked[p] === '{') depth++;
			else if (masked[p] === '}') depth--;
			p++;
		}
		const fnBody = masked.slice(bodyStart, p);
		for (const fsMatch of fnBody.matchAll(/\bstd::fs::([A-Za-z_][A-Za-z0-9_]*)/g)) {
			const absOffset = bodyStart + fsMatch.index;
			const line = masked.slice(0, absOffset).split('\n').length;
			const lastNl = masked.lastIndexOf('\n', absOffset);
			const col = absOffset - lastNl;
			if (isLineEnabled(lines, line) && !ignored.has(line)) {
				report(
					'rust-async-blocking-fs',
					line,
					col,
					`blocking \`std::fs::${fsMatch[1]}\` inside \`async fn ${fnName}\` (use \`tokio::fs\` or \`spawn_blocking\`)`,
					{enclosing: fnName, symbol: `std::fs::${fsMatch[1]}`},
				);
			}
		}
	}
}

function maskGleamCode(source) {
	const chars = source.split('');
	let i = 0;
	while (i < chars.length) {
		if (chars[i] === '/' && chars[i + 1] === '/') {
			while (i < chars.length && chars[i] !== '\n') chars[i++] = ' ';
		} else if (chars[i] === '"') {
			chars[i++] = ' ';
			while (i < chars.length && chars[i] !== '"') {
				if (chars[i] === '\\' && i + 1 < chars.length) {
					if (chars[i + 1] !== '\n') chars[i + 1] = ' ';
					chars[i++] = ' ';
				}
				if (chars[i] !== '\n') chars[i] = ' ';
				i++;
			}
			if (i < chars.length) chars[i++] = ' ';
		} else {
			i++;
		}
	}
	return chars.join('');
}

function checkGleamForkTestSleep(file, source, lines, ignored, report) {
	if (!file.startsWith('fluxer_gateway/test/') || !file.includes('fork') || !file.endsWith('.gleam')) {
		return;
	}
	const masked = maskGleamCode(source);
	const testFnRe = /\bpub\s+fn\s+([a-zA-Z0-9_]+_test)\s*\(/g;
	for (const m of masked.matchAll(testFnRe)) {
		const fnName = m[1];
		let idx = m.index + m[0].length;
		let bodyStart = -1;
		while (idx < masked.length) {
			if (masked[idx] === '{') {
				bodyStart = idx;
				break;
			}
			idx++;
		}
		if (bodyStart === -1) continue;
		let depth = 1;
		let p = bodyStart + 1;
		while (p < masked.length && depth > 0) {
			if (masked[p] === '{') depth++;
			else if (masked[p] === '}') depth--;
			p++;
		}
		const body = masked.slice(bodyStart, p);
		for (const sleepMatch of body.matchAll(/\bprocess\.sleep\s*\(/g)) {
			const absOffset = bodyStart + sleepMatch.index;
			const line = masked.slice(0, absOffset).split('\n').length;
			const lastNl = masked.lastIndexOf('\n', absOffset);
			const col = absOffset - lastNl;
			if (isLineEnabled(lines, line) && !ignored.has(line)) {
				report(
					'gleam-fork-test-sleep',
					line,
					col,
					`\`process.sleep()\` inside fork test \`${fnName}\` makes tests slow/flaky (synchronize on actor/monitor state instead)`,
					{enclosing: fnName, symbol: 'process.sleep'},
				);
			}
		}
	}
}

/**
 * Checks a single monorepo file on the given lines ('all' or Set<number>).
 * @param {string} relFile Path relative to repository root (e.g. `fluxer_api/src/...`)
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @param {{rules?: Set<string>; reviewed?: import('./fork-lint-reviewed.mjs').ReviewedLintCatalog | null | undefined}} [options]
 * @returns {Array<string>}
 */
export function lintBackendDesktopFile(relFile, source, lines = 'all', options = {}) {
	const file = relFile.replace(/\\/g, '/');
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	const activeRules = options.rules ?? ALL_BACKEND_DESKTOP_RULES;
	const reviewed = options.reviewed ?? null;
	const repoFile = normalizeRepoRelPath(file, '');
	const sourceLines = source.split('\n');
	const problems = [];
	const report = (rule, line, col, message, meta = {}) => {
		const sourceLine = (sourceLines[line - 1] ?? '').trim();
		if (
			reviewed?.matches({
				linter: 'backend-desktop',
				rule,
				file: repoFile,
				enclosing: meta.enclosing ?? '',
				symbol: meta.symbol,
				target: meta.target,
				sourceLine,
			})
		) {
			return;
		}
		problems.push(`${file}:${line}:${col}: [${rule}] ${message}`);
	};

	if (file.endsWith('.rs')) {
		if (activeRules.has('rust-async-blocking-fs')) {
			checkRustAsyncBlockingFs(file, source, lines, collectIgnoredLines(null, source), report);
		}
		return problems;
	}

	if (file.endsWith('.gleam')) {
		if (activeRules.has('gleam-fork-test-sleep')) {
			checkGleamForkTestSleep(file, source, lines, collectIgnoredLines(null, source), report);
		}
		return problems;
	}

	if (!/\.(ts|tsx|js|jsx|mjs)$/.test(file) || file.endsWith('.d.ts')) return [];

	let ast;
	try {
		ast = parse(source, {sourceType: 'module', plugins: ['typescript', 'jsx', 'decorators'], errorRecovery: true});
	} catch (error) {
		return [`${file}: could not parse: ${error.message}`];
	}
	const ignored = collectIgnoredLines(ast.comments ?? [], source);
	const isTest = TEST_FILE_RE.test(file);

	if (file.startsWith('fluxer_api/src/')) {
		if (!isTest && activeRules.has('non-atomic-index-write')) {
			checkNonAtomicIndexWrite(source, ast, lines, ignored, report);
		}
		if (!isTest && activeRules.has('promise-race-timeout-leak')) {
			checkPromiseRaceTimeoutLeak(source, ast, lines, ignored, report);
		}
		if (activeRules.has('api-controller-hygiene')) {
			checkApiControllerHygiene(file, source, ast, lines, ignored, report);
		}
	}

	if (!isTest && file.startsWith('packages/schema/src/domains/')) {
		if (activeRules.has('zod-schema-trap')) {
			checkZodSchemas(source, ast, lines, ignored, report);
		}
	}

	if (!isTest && file.startsWith('fluxer_desktop/src/')) {
		if (activeRules.has('promise-race-timeout-leak')) {
			checkPromiseRaceTimeoutLeak(source, ast, lines, ignored, report);
		}
		if (file.startsWith('fluxer_desktop/src/main/')) {
			if (activeRules.has('desktop-ipc-sender')) {
				checkDesktopIpcSender(source, ast, lines, ignored, report);
			}
			if (activeRules.has('desktop-window-safety')) {
				checkDesktopWindowSafety(file, source, ast, lines, ignored, report);
			}
		}
	}

	return problems.sort((a, b) => {
		const ma = /^[^:]+:(\d+):(\d+):/.exec(a);
		const mb = /^[^:]+:(\d+):(\d+):/.exec(b);
		if (!ma || !mb) return a.localeCompare(b);
		return Number(ma[1]) - Number(mb[1]) || Number(ma[2]) - Number(mb[2]);
	});
}

function optionValue(args, name, fallback) {
	const index = args.indexOf(name);
	return index === -1 ? fallback : args[index + 1];
}

function parseRulesOption(args) {
	const raw = optionValue(args, '--rule', '');
	if (!raw) return ALL_BACKEND_DESKTOP_RULES;
	const chosen = new Set(
		raw
			.split(',')
			.map((s) => s.trim())
			.filter(Boolean),
	);
	for (const r of chosen) {
		if (!ALL_BACKEND_DESKTOP_RULES.has(r)) {
			console.error(`Unknown rule: ${r}. Available: ${[...ALL_BACKEND_DESKTOP_RULES].join(', ')}`);
			process.exit(2);
		}
	}
	return chosen;
}

function normalizeCliPath(arg) {
	const abs = path.isAbsolute(arg) ? arg : path.resolve(APP_DIR, arg);
	return path.relative(REPO_ROOT, abs).replace(/\\/g, '/');
}

function main() {
	const {reviewedPath, includeReviewed, checkReviewed, restArgs} = extractReviewedCliArgs(process.argv.slice(2));
	const all = restArgs.includes('--all') || checkReviewed;
	const upstream = optionValue(restArgs, '--upstream', 'upstream/main');
	const rules = parseRulesOption(restArgs);
	const given = restArgs.filter(
		(arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream' && args[i - 1] !== '--rule',
	);
	const catalog = loadReviewedCatalogOrExit(reviewedPath, {includeReviewed, checkReviewed});

	let targets;
	if (all) {
		const files =
			given.length > 0
				? given.map(normalizeCliPath)
				: git(
						'ls-files',
						'--',
						'fluxer_api/src',
						'packages/schema/src/domains',
						'fluxer_desktop/src',
						'fluxer_gateway/test',
						'*.rs',
					)
						.split('\n')
						.filter(Boolean);
		targets = new Map(files.map((file) => [file, 'all']));
	} else {
		const changes = forkChanges(upstream);
		targets =
			given.length > 0
				? new Map(given.map((arg) => [normalizeCliPath(arg), changes.get(normalizeCliPath(arg)) ?? new Set()]))
				: changes;
	}

	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		const abs = path.join(REPO_ROOT, file);
		if (fs.existsSync(abs)) {
			problems.push(...lintBackendDesktopFile(file, fs.readFileSync(abs, 'utf8'), lines, {rules, reviewed: catalog}));
		}
	}

	finishReviewedCheckOrNotes({
		linter: 'backend-desktop',
		catalog,
		reviewedPath,
		checkReviewed,
		reportAllSummary: all,
		allFilesScanned: given.length === 0,
		rules,
	});

	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} backend/desktop safety violation(s). Fix the underlying issue, mark fork lines with \`// safety-lint-ignore: <reason>\`, or record reviewed upstream entries in \`fluxer_app/scripts/fork-lint-reviewed.json\`.`,
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
