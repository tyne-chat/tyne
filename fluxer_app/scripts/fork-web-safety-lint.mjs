// Fork: AST safety checks for React/MobX reactivity, timers, effect cleanups, Web Storage,
// Messages reads, and zoom-blind viewport queries in fluxer_app (tyne-chat/tyne#947).
//
//   node scripts/fork-web-safety-lint.mjs [--upstream <git ref>] [--all] [--rule <r1,r2>] [<file>...]
//
// Rules (all run in a single Babel AST parse pass per JS/TS file unless `--rule` filters):
// 1. `missing-observer`: React component in `.tsx` reading a MobX store during render without `observer()`.
// 2. `mobx-stale-memo`: `useMemo(() => ..., [deps])` reading a MobX store without listing the store
//    or a version/epoch/revision dep (`tyne-chat/tyne#937`).
// 3. `uncaptured-timer`: uncaptured `setTimeout` calling a `useState` setter or uncaptured `setInterval`
//    inside a component/hook (`tyne-chat/tyne#861`).
// 4. `effect-missing-cleanup`: `useEffect`/`useLayoutEffect` calling `addEventListener`, `setInterval`,
//    or MobX `reaction`/`autorun` without returning a cleanup function.
// 5. `raw-web-storage`: direct `localStorage`/`sessionStorage` outside `src/features/platform/state/`
//    (`tyne-chat/tyne#140`).
// 6. `messages-untracked-read`: `observer()` component calling `Messages.getMessage`/`getMessages`/
//    `getCachedMessages` during render without reading `Messages.version`.
// 7. `zoom-blind-viewport`: `window.innerWidth`/`innerHeight` comparisons or pixel `matchMedia()`
//    queries without `getAppRemScale()`, and `@media (...px)` width/height queries on fork CSS lines
//    (`tyne-chat/tyne#639`).
//
// Suppress a deliberate exception with `// web-safety-ignore: <reason>` (or `/* px-ok: <reason> */`
// on CSS `@media` lines) on its line or the line immediately above.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parse} from '@babel/parser';
import {
	enclosingAstSymbol,
	extractReviewedCliArgs,
	finishReviewedCheckOrNotes,
	loadReviewedCatalogOrExit,
	normalizeRepoRelPath,
} from './fork-lint-reviewed.mjs';

export const ALL_WEB_SAFETY_RULES = new Set([
	'missing-observer',
	'mobx-stale-memo',
	'uncaptured-timer',
	'effect-missing-cleanup',
	'raw-web-storage',
	'messages-untracked-read',
	'zoom-blind-viewport',
]);

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_RE = /^src\/.*\.(ts|tsx|js|jsx|mjs|css)$/;
const SCRIPT_RE = /\.(ts|tsx|js|jsx|mjs)$/;
const SKIPPED_RE =
	/(\.test\.|\.spec\.|\.stories\.|\.bench\.|\/__tests__\/|\/__fixtures__\/|\/test\/|\/testing\/|\.d\.ts$)/;
const GENERATED_RE = /^\/[/*] ?(Generated by |@generated|GENERATED CODE)/m;
const IGNORE_RE = /web-safety-ignore:\s*\S/;
const PX_OK_RE = /px-ok:\s*\S/;

const STATIC_STORES = new Set(['RuntimeConfig', 'Experiments', 'DeveloperOptions', 'LayoutState']);
const ACTION_VERB_RE =
	/^(set|toggle|clear|reset|add|remove|delete|update|open|close|mark|record|track|bump|notify|register|unregister|subscribe|unsubscribe|fetch|load|ensure|dismiss|persist)[A-Z]/;
const HANDLER_PROP_RE = /^(on|handle)[A-Z]/;
const CONSTANT_PROP_RE = /^[A-Z0-9_]+$/;
const SYNC_COLLECTION_CALLBACK_RE = /^(map|filter|find|findIndex|some|every|reduce|reduceRight|flatMap|forEach|sort)$/;
const REACTIVITY_DEP_RE = /(version|epoch|revision|tick|count)/i;
const CSS_MEDIA_PX_RE = /^\s*@media\b.*\b(min|max)-(width|height)\s*:\s*\d+(?:\.\d+)?px\b/i;

let cachedMobxModules;

function walkFiles(dir, out = []) {
	if (!fs.existsSync(dir)) return out;
	for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
		const full = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			walkFiles(full, out);
		} else if (entry.isFile()) {
			out.push(full);
		}
	}
	return out;
}

/**
 * Discovers MobX state modules under `fluxer_app/src` as `@app/...` specifiers without extension.
 * @param {string} [appDir]
 * @returns {Set<string>}
 */
export function discoverMobxStateModules(appDir = APP_DIR) {
	if (appDir === APP_DIR && cachedMobxModules) return cachedMobxModules;
	const modules = new Set();
	const featuresDir = path.join(appDir, 'src', 'features');
	for (const full of walkFiles(featuresDir)) {
		const rel = path.relative(appDir, full).replace(/\\/g, '/');
		if (!rel.includes('/state/') || !/\.(ts|tsx)$/.test(rel) || SKIPPED_RE.test(rel)) continue;
		const src = fs.readFileSync(full, 'utf8');
		if (/\b(makeAutoObservable|makeObservable|observable)\b/.test(src)) {
			modules.add(`@app/${rel.slice('src/'.length).replace(/\.(ts|tsx)$/, '')}`);
		}
	}
	if (appDir === APP_DIR) cachedMobxModules = modules;
	return modules;
}

function git(...args) {
	return execFileSync('git', args, {cwd: APP_DIR, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	for (const line of git('diff', '-U0', '--no-color', '--no-renames', '--diff-filter=AM', base, '--', 'src').split(
		'\n',
	)) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/fluxer_app/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', 'src').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

function identName(node) {
	if (!node) return undefined;
	if (node.type === 'Identifier') return node.name;
	if (node.type === 'MemberExpression' || node.type === 'OptionalMemberExpression') {
		return identName(node.property);
	}
	return undefined;
}

function isFnNode(node) {
	return (
		node.type === 'FunctionDeclaration' || node.type === 'FunctionExpression' || node.type === 'ArrowFunctionExpression'
	);
}

function resolveImportToAppPath(file, specifier) {
	const stripped = specifier.replace(/\.(ts|tsx|js|jsx|mjs)$/, '').replace(/\/index$/, '');
	if (stripped.startsWith('@app/')) return stripped;
	if (stripped.startsWith('./') || stripped.startsWith('../')) {
		const normalizedFile = file.replace(/\\/g, '/');
		const resolved = path.posix.normalize(path.posix.join(path.posix.dirname(normalizedFile), stripped));
		if (resolved.startsWith('src/')) {
			return `@app/${resolved.slice('src/'.length)}`;
		}
	}
	return stripped;
}

function lintCssSource(file, source, lines, activeRules, reviewed = null) {
	if (!activeRules.has('zoom-blind-viewport')) return [];
	const problems = [];
	const repoFile = normalizeRepoRelPath(file);
	const rawLines = source.split('\n');
	for (let i = 0; i < rawLines.length; i++) {
		const ln = i + 1;
		if (lines !== 'all' && !lines.has(ln)) continue;
		const lineText = rawLines[i];
		const prevText = i > 0 ? rawLines[i - 1] : '';
		if (IGNORE_RE.test(lineText) || IGNORE_RE.test(prevText) || PX_OK_RE.test(lineText) || PX_OK_RE.test(prevText)) {
			continue;
		}
		if (CSS_MEDIA_PX_RE.test(lineText)) {
			const trimmed = lineText.trim();
			if (
				reviewed?.matches({
					linter: 'web-safety',
					rule: 'zoom-blind-viewport',
					file: repoFile,
					enclosing: '',
					symbol: trimmed,
					target: '@media',
					sourceLine: trimmed,
				})
			) {
				continue;
			}
			problems.push(
				`${file}:${ln}:1: [zoom-blind-viewport] CSS @media pixel query \`${trimmed}\` ignores desktop zoom (use @container in rem or mark with \`/* px-ok: <reason> */\`; tyne-chat/tyne#639)`,
			);
		}
	}
	return problems;
}

function isLineEnabled(lines, line) {
	return Boolean(line && (lines === 'all' || lines.has(line)));
}

function isDepsTrackingStore(depsNode, depsSrc, storeIdent) {
	if (REACTIVITY_DEP_RE.test(depsSrc)) return true;
	let found = false;
	const scan = (n) => {
		if (!n || typeof n.type !== 'string' || found) return;
		if (n.type === 'Identifier' && n.name === storeIdent) {
			found = true;
			return;
		}
		for (const k of Object.keys(n)) {
			if (k === 'loc' || k.endsWith('Comments')) continue;
			const v = n[k];
			if (Array.isArray(v)) v.forEach(scan);
			else if (v && typeof v === 'object' && typeof v.type === 'string') scan(v);
		}
	};
	scan(depsNode);
	return found;
}

/**
 * Checks a single file's source on the given lines ('all' or Set<number>).
 * @param {string} file
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @param {{rules?: Set<string>; mobxStateModules?: Set<string>; reviewed?: import('./fork-lint-reviewed.mjs').ReviewedLintCatalog | null | undefined}} [options]
 * @returns {Array<string>}
 */
export function lintWebSafetySource(file, source, lines = 'all', options = {}) {
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	const activeRules = options.rules ?? ALL_WEB_SAFETY_RULES;
	const reviewed = options.reviewed ?? null;
	const normalizedFile = file.replace(/\\/g, '/');
	const repoFile = normalizeRepoRelPath(normalizedFile);

	if (normalizedFile.endsWith('.css')) {
		return lintCssSource(normalizedFile, source, lines, activeRules, reviewed);
	}
	if (!SCRIPT_RE.test(normalizedFile)) return [];

	const sourceLines = source.split('\n');
	const pushProblem = (rule, line, col, message, meta = {}) => {
		const sourceLine = (sourceLines[line - 1] ?? '').trim();
		if (
			reviewed?.matches({
				linter: 'web-safety',
				rule,
				file: repoFile,
				enclosing: meta.enclosing ?? '',
				symbol: meta.symbol,
				target: meta.target,
				sourceLine,
			})
		) {
			return;
		}
		problems.push(`${normalizedFile}:${line}:${col}: [${rule}] ${message}`);
	};

	let ast;
	try {
		ast = parse(source, {sourceType: 'module', plugins: ['typescript', 'jsx', 'decorators'], errorRecovery: true});
	} catch (error) {
		return [`${normalizedFile}: could not parse: ${error.message}`];
	}

	const ignored = new Set();
	for (const comment of ast.comments ?? []) {
		if (IGNORE_RE.test(comment.value)) {
			ignored.add(comment.loc.end.line);
			ignored.add(comment.loc.end.line + 1);
		}
	}

	const mobxStateModules = options.mobxStateModules ?? discoverMobxStateModules();
	const mobxImports = new Map();
	const mobxReactiveHelpers = new Set();
	let messagesIdent = null;
	const importsZoomScale = /\bgetAppRemScale\b/.test(source);

	for (const stmt of ast.program.body) {
		if (stmt.type !== 'ImportDeclaration' || stmt.importKind === 'type') continue;
		const rawMod = stmt.source.value;
		const resolved = resolveImportToAppPath(normalizedFile, rawMod);
		if (mobxStateModules.has(resolved)) {
			for (const sp of stmt.specifiers) {
				if (sp.importKind !== 'type') mobxImports.set(sp.local.name, resolved);
			}
		}
		if (resolved === '@app/features/messaging/state/MessagingMessages') {
			for (const sp of stmt.specifiers) {
				if (sp.type === 'ImportDefaultSpecifier') messagesIdent = sp.local.name;
			}
		}
		if (rawMod === 'mobx') {
			for (const sp of stmt.specifiers) {
				if (
					sp.type === 'ImportSpecifier' &&
					sp.importKind !== 'type' &&
					(sp.imported.name === 'reaction' || sp.imported.name === 'autorun')
				) {
					mobxReactiveHelpers.add(sp.local.name);
				}
			}
		}
	}

	// Pre-pass: find components wrapped later via `observer(Comp)` and `useState` setters.
	const observerWrappedNames = new Set();
	const stateSetterNames = new Set();
	const scanPre = (node) => {
		if (!node || typeof node.type !== 'string') return;
		if (node.type === 'CallExpression') {
			const cn = identName(node.callee);
			if ((cn === 'observer' || cn === 'Observer') && node.arguments[0]?.type === 'Identifier') {
				observerWrappedNames.add(node.arguments[0].name);
			}
		}
		if (
			node.type === 'VariableDeclarator' &&
			node.id?.type === 'ArrayPattern' &&
			node.init?.type === 'CallExpression' &&
			identName(node.init.callee) === 'useState' &&
			node.id.elements[1]?.type === 'Identifier'
		) {
			stateSetterNames.add(node.id.elements[1].name);
		}
		for (const key of Object.keys(node)) {
			if (key === 'loc' || key.endsWith('Comments')) continue;
			const value = node[key];
			if (Array.isArray(value)) value.forEach(scanPre);
			else if (value && typeof value === 'object' && typeof value.type === 'string') scanPre(value);
		}
	};
	scanPre(ast.program);

	const problems = [];
	const ancestors = [];
	const fnStack = [];
	const compStack = [];
	const allowRawStorage = normalizedFile.includes('src/features/platform/state/');
	const isChannelMessagesCacheHost = normalizedFile.endsWith('src/features/channel/components/ChannelMessages.tsx');

	const visit = (node) => {
		if (!node || typeof node.type !== 'string') return;
		const parent = ancestors.at(-1);
		const grandParent = ancestors.at(-2);
		const line = node.loc?.start.line;
		const col = (node.loc?.start.column ?? 0) + 1;

		// Rule: raw-web-storage
		if (
			activeRules.has('raw-web-storage') &&
			!allowRawStorage &&
			node.type === 'Identifier' &&
			(node.name === 'localStorage' || node.name === 'sessionStorage') &&
			isLineEnabled(lines, line) &&
			!ignored.has(line)
		) {
			const isNonGlobalProp =
				(parent?.type === 'MemberExpression' || parent?.type === 'OptionalMemberExpression') &&
				parent.property === node &&
				!parent.computed &&
				!(
					parent.object.type === 'Identifier' &&
					(parent.object.name === 'window' || parent.object.name === 'globalThis')
				);
			const isObjKey = parent?.type === 'ObjectProperty' && parent.key === node && !parent.computed;
			const isParamOrBinding =
				parent?.type === 'VariableDeclarator' && parent.id === node
					? true
					: isFnNode(parent) && parent.params.includes(node);
			const isTypePos = ancestors.some((a) => a.type.startsWith('TS'));
			if (!isNonGlobalProp && !isObjKey && !isParamOrBinding && !isTypePos) {
				pushProblem(
					'raw-web-storage',
					line,
					col,
					`direct \`${node.name}\` usage fails in production builds where storage is stripped (use AppStorage / makePersistent; tyne-chat/tyne#140)`,
					{enclosing: enclosingAstSymbol(ancestors), symbol: node.name},
				);
			}
		}

		// Rule: zoom-blind-viewport (JS/TS)
		if (
			activeRules.has('zoom-blind-viewport') &&
			!importsZoomScale &&
			isLineEnabled(lines, line) &&
			!ignored.has(line)
		) {
			if (
				node.type === 'MemberExpression' &&
				node.object.type === 'Identifier' &&
				node.object.name === 'window' &&
				node.property.type === 'Identifier' &&
				(node.property.name === 'innerWidth' || node.property.name === 'innerHeight') &&
				parent?.type === 'BinaryExpression' &&
				(parent.operator === '<' || parent.operator === '<=' || parent.operator === '>' || parent.operator === '>=')
			) {
				pushProblem(
					'zoom-blind-viewport',
					line,
					col,
					`\`window.${node.property.name}\` comparison without \`getAppRemScale()\` ignores desktop zoom (tyne-chat/tyne#639)`,
					{enclosing: enclosingAstSymbol(ancestors), target: `window.${node.property.name}`},
				);
			} else if (
				(node.type === 'CallExpression' || node.type === 'OptionalCallExpression') &&
				identName(node.callee) === 'matchMedia' &&
				node.arguments[0]
			) {
				const argSrc = source.slice(node.arguments[0].start, node.arguments[0].end);
				if (/\b(min|max)-(width|height)\s*:\s*\d+(?:\.\d+)?px\b/i.test(argSrc)) {
					pushProblem(
						'zoom-blind-viewport',
						line,
						col,
						`\`matchMedia(${argSrc})\` without \`getAppRemScale()\` ignores desktop zoom (tyne-chat/tyne#639)`,
						{enclosing: enclosingAstSymbol(ancestors), target: 'matchMedia()'},
					);
				}
			}
		}

		const isFn = isFnNode(node);
		if (isFn) {
			let name =
				node.id?.name ??
				(parent?.type === 'VariableDeclarator' && parent.id?.type === 'Identifier' ? parent.id.name : '');
			let isObs = Boolean(name && observerWrappedNames.has(name));
			for (let i = ancestors.length - 1; i >= Math.max(0, ancestors.length - 4); i--) {
				const anc = ancestors[i];
				if (anc.type === 'CallExpression') {
					const cn = identName(anc.callee);
					if (cn === 'observer' || cn === 'Observer') isObs = true;
					if (!name && ancestors[i - 1]?.type === 'VariableDeclarator' && ancestors[i - 1].id?.type === 'Identifier') {
						name = ancestors[i - 1].id.name;
						if (observerWrappedNames.has(name)) isObs = true;
					}
				}
			}
			let hookCall = null;
			if (parent?.type === 'CallExpression' && parent.arguments[0] === node) {
				const hname = identName(parent.callee);
				if (
					hname === 'useMemo' ||
					hname === 'useMobxMemo' ||
					hname === 'useEffect' ||
					hname === 'useLayoutEffect' ||
					hname === 'useCallback'
				) {
					hookCall = {hook: hname, call: parent};
				}
			}
			const parentFn = fnStack.at(-1);
			const isIife =
				(parent?.type === 'CallExpression' || parent?.type === 'OptionalCallExpression') && parent.callee === node;
			const isSyncCollectionCallback =
				parent?.type === 'CallExpression' &&
				parent.arguments[0] === node &&
				parent.callee.type === 'MemberExpression' &&
				parent.callee.property.type === 'Identifier' &&
				SYNC_COLLECTION_CALLBACK_RE.test(parent.callee.property.name);
			const hasEnclosingFn = fnStack.length > 0;
			const isTopComp = !hasEnclosingFn && /^[A-Z][A-Za-z0-9]*$/.test(name) && normalizedFile.endsWith('.tsx');
			const isRenderPhaseHook =
				!hasEnclosingFn && /^use[A-Z][A-Za-z0-9]*$/.test(name) && normalizedFile.endsWith('.tsx');
			const runsInRender =
				isTopComp ||
				isRenderPhaseHook ||
				(Boolean(parentFn?.runsInRender) &&
					(hookCall?.hook === 'useMemo' || hookCall?.hook === 'useMobxMemo' || isIife || isSyncCollectionCallback));
			const runsInMemo =
				hookCall?.hook === 'useMemo' || (Boolean(parentFn?.runsInMemo) && (isIife || isSyncCollectionCallback));

			const entry = {
				node,
				name,
				isTopComp,
				isObs,
				hookCall,
				runsInRender,
				runsInMemo,
				hasJSX: false,
				renderStoreReads: [],
				memoStoreReads: [],
				readsMessagesGet: null,
				readsMessagesVersion: false,
				// Concise arrow `useEffect(() => reaction(...), [deps])` returns the disposer directly.
				hasCleanupReturn: node.body?.type !== 'BlockStatement',
				effectResources: [],
			};
			fnStack.push(entry);
			if (isTopComp) compStack.push(entry);
		}

		const curFn = fnStack.at(-1);
		const curComp = compStack.at(-1);
		if (curComp && (node.type === 'JSXElement' || node.type === 'JSXFragment')) {
			curComp.hasJSX = true;
		}

		// Track MobX store reads and MessagingMessages reads
		if (
			curFn &&
			(node.type === 'MemberExpression' || node.type === 'OptionalMemberExpression') &&
			node.object.type === 'Identifier' &&
			!ancestors.some((a) => a.type.startsWith('TS'))
		) {
			const obj = node.object.name;
			const prop = node.property.type === 'Identifier' ? node.property.name : '';
			if (
				prop &&
				mobxImports.has(obj) &&
				!STATIC_STORES.has(obj) &&
				!ACTION_VERB_RE.test(prop) &&
				!HANDLER_PROP_RE.test(prop) &&
				!CONSTANT_PROP_RE.test(prop)
			) {
				const isEventPropRef =
					parent?.type === 'JSXExpressionContainer' &&
					grandParent?.type === 'JSXAttribute' &&
					grandParent.name?.type === 'JSXIdentifier' &&
					/^on[A-Z]/.test(grandParent.name.name);
				if (!isEventPropRef) {
					const enclosing = enclosingAstSymbol(ancestors);
					if (curFn.runsInRender && curComp) {
						curComp.renderStoreReads.push({store: obj, prop, line, col, enclosing});
					}
					if (curFn.runsInMemo) {
						// Record against nearest enclosing useMemo fn
						for (let i = fnStack.length - 1; i >= 0; i--) {
							if (fnStack[i].hookCall?.hook === 'useMemo') {
								fnStack[i].memoStoreReads.push({store: obj, prop, line, col, enclosing});
								break;
							}
						}
					}
				}
			}

			if (messagesIdent && obj === messagesIdent && curComp && curFn.runsInRender) {
				if (prop === 'getMessage' || prop === 'getMessages' || prop === 'getCachedMessages') {
					curComp.readsMessagesGet ??= {prop, line, col, enclosing: enclosingAstSymbol(ancestors)};
				}
				if (prop === 'version') {
					curComp.readsMessagesVersion = true;
				}
			}
		}

		// Rule: uncaptured-timer
		if (
			activeRules.has('uncaptured-timer') &&
			node.type === 'CallExpression' &&
			isLineEnabled(lines, line) &&
			!ignored.has(line)
		) {
			const isExprStmt =
				parent?.type === 'ExpressionStatement' ||
				(parent?.type === 'UnaryExpression' &&
					parent.operator === 'void' &&
					grandParent?.type === 'ExpressionStatement');
			if (isExprStmt) {
				let timerName;
				if (node.callee.type === 'Identifier') {
					timerName = node.callee.name;
				} else if (
					node.callee.type === 'MemberExpression' &&
					node.callee.object.type === 'Identifier' &&
					(node.callee.object.name === 'window' || node.callee.object.name === 'globalThis') &&
					node.callee.property.type === 'Identifier'
				) {
					timerName = node.callee.property.name;
				}
				if (timerName === 'setTimeout' || timerName === 'setInterval') {
					const inReactBody = fnStack.some((fn) => /^[A-Z]/.test(fn.name) || /^use[A-Z]/.test(fn.name));
					const inEffectBody = curFn?.hookCall?.hook === 'useEffect' || curFn?.hookCall?.hook === 'useLayoutEffect';
					const cb = node.arguments[0];
					if (inReactBody && cb) {
						const cbSrc = source.slice(cb.start, cb.end);
						const callsSetter = [...stateSetterNames].some((s) => new RegExp(`\\b${s}\\s*\\(`).test(cbSrc));
						if ((timerName === 'setInterval' && !inEffectBody) || callsSetter) {
							const msg =
								`uncaptured \`${timerName}\` ${timerName === 'setInterval' ? '' : 'calling React state setter '}cannot be cleared on unmount (store timer ID in a ref and clear in useEffect cleanup; tyne-chat/tyne#861)`.replace(
									'  ',
									' ',
								);
							pushProblem('uncaptured-timer', line, col, msg, {
								enclosing: enclosingAstSymbol(ancestors),
								target: `${timerName}()`,
							});
						}
					}
				}
			}
		}

		// Track resources & cleanup inside useEffect / useLayoutEffect
		if (curFn?.hookCall && (curFn.hookCall.hook === 'useEffect' || curFn.hookCall.hook === 'useLayoutEffect')) {
			if (node.type === 'ReturnStatement' && node.argument) {
				curFn.hasCleanupReturn = true;
			}
			if (node.type === 'CallExpression') {
				const calleeProp = identName(node.callee);
				const isDirectTimer =
					calleeProp === 'setInterval' &&
					(node.callee.type === 'Identifier' ||
						(node.callee.type === 'MemberExpression' &&
							node.callee.object.type === 'Identifier' &&
							(node.callee.object.name === 'window' || node.callee.object.name === 'globalThis')));
				const isListener =
					calleeProp === 'addEventListener' &&
					node.callee.type === 'MemberExpression' &&
					!/\bonce\s*:\s*true\b/.test(source.slice(node.start, node.end)) &&
					!/\bsignal\b/.test(source.slice(node.start, node.end));
				const isMobxReaction = node.callee.type === 'Identifier' && mobxReactiveHelpers.has(node.callee.name);
				if (isDirectTimer || isListener || isMobxReaction) {
					curFn.effectResources.push({kind: calleeProp, line, col, enclosing: enclosingAstSymbol(ancestors)});
				}
			}
		}

		ancestors.push(node);
		for (const key of Object.keys(node)) {
			if (key === 'loc' || key.endsWith('Comments')) continue;
			const value = node[key];
			if (Array.isArray(value)) value.forEach(visit);
			else if (value && typeof value === 'object' && typeof value.type === 'string') visit(value);
		}
		ancestors.pop();

		if (isFn) {
			const popped = fnStack.pop();
			if (popped.isTopComp) compStack.pop();

			// Rule: mobx-stale-memo
			if (
				activeRules.has('mobx-stale-memo') &&
				popped.hookCall?.hook === 'useMemo' &&
				popped.memoStoreReads.length > 0 &&
				popped.hookCall.call.arguments.length >= 2
			) {
				const depsNode = popped.hookCall.call.arguments[1];
				const depsSrc = source.slice(depsNode.start, depsNode.end);
				for (const read of popped.memoStoreReads) {
					if (
						isLineEnabled(lines, read.line) &&
						!ignored.has(read.line) &&
						!isDepsTrackingStore(depsNode, depsSrc, read.store)
					) {
						pushProblem(
							'mobx-stale-memo',
							read.line,
							read.col,
							`\`useMemo\` reads \`${read.store}.${read.prop}\` without listing \`${read.store}\` or a reactive dep in its dependency array (breaks MobX updates once memoized; tyne-chat/tyne#937)`,
							{enclosing: read.enclosing, symbol: `${read.store}.${read.prop}`, target: 'useMemo'},
						);
					}
				}
			}

			// Rule: missing-observer
			if (
				activeRules.has('missing-observer') &&
				popped.isTopComp &&
				popped.hasJSX &&
				!popped.isObs &&
				popped.renderStoreReads.length > 0
			) {
				const relevant = popped.renderStoreReads.filter(
					(read) => isLineEnabled(lines, read.line) && !ignored.has(read.line),
				);
				if (relevant.length > 0) {
					const first = relevant[0];
					pushProblem(
						'missing-observer',
						first.line,
						first.col,
						`component \`${popped.name}\` reads \`${first.store}.${first.prop}\` during render without \`observer()\` (never re-renders on store changes)`,
						{enclosing: popped.name, symbol: `${first.store}.${first.prop}`},
					);
				}
			}

			// Rule: messages-untracked-read
			if (
				activeRules.has('messages-untracked-read') &&
				!isChannelMessagesCacheHost &&
				popped.isTopComp &&
				popped.isObs &&
				popped.readsMessagesGet &&
				!popped.readsMessagesVersion &&
				isLineEnabled(lines, popped.readsMessagesGet.line) &&
				!ignored.has(popped.readsMessagesGet.line)
			) {
				const read = popped.readsMessagesGet;
				pushProblem(
					'messages-untracked-read',
					read.line,
					read.col,
					`\`${popped.name}\` calls \`${messagesIdent}.${read.prop}()\` during render without reading \`${messagesIdent}.version\` (Messages is not deep-observable)`,
					{enclosing: popped.name, symbol: `${messagesIdent}.${read.prop}()`},
				);
			}

			// Rule: effect-missing-cleanup
			if (
				activeRules.has('effect-missing-cleanup') &&
				popped.hookCall &&
				(popped.hookCall.hook === 'useEffect' || popped.hookCall.hook === 'useLayoutEffect') &&
				popped.effectResources.length > 0 &&
				!popped.hasCleanupReturn
			) {
				for (const res of popped.effectResources) {
					if (isLineEnabled(lines, res.line) && !ignored.has(res.line)) {
						pushProblem(
							'effect-missing-cleanup',
							res.line,
							res.col,
							`\`${popped.hookCall.hook}\` registers \`${res.kind}()\` without returning a cleanup function`,
							{enclosing: res.enclosing, symbol: `${res.kind}()`, target: popped.hookCall.hook},
						);
					}
				}
			}
		}
	};

	visit(ast.program);
	return problems;
}

function optionValue(args, name, fallback) {
	const index = args.indexOf(name);
	return index === -1 ? fallback : args[index + 1];
}

function parseRulesOption(args) {
	const raw = optionValue(args, '--rule', '');
	if (!raw) return ALL_WEB_SAFETY_RULES;
	const chosen = new Set(
		raw
			.split(',')
			.map((s) => s.trim())
			.filter(Boolean),
	);
	for (const r of chosen) {
		if (!ALL_WEB_SAFETY_RULES.has(r)) {
			console.error(`Unknown rule: ${r}. Available: ${[...ALL_WEB_SAFETY_RULES].join(', ')}`);
			process.exit(2);
		}
	}
	return chosen;
}

function main() {
	const {reviewedPath, includeReviewed, checkReviewed, restArgs} = extractReviewedCliArgs(process.argv.slice(2));
	const all = restArgs.includes('--all') || checkReviewed;
	const upstream = optionValue(restArgs, '--upstream', 'upstream/main');
	const rules = parseRulesOption(restArgs);
	const explicitRules = restArgs.includes('--rule');
	const given = restArgs.filter(
		(arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream' && args[i - 1] !== '--rule',
	);
	const catalog = loadReviewedCatalogOrExit(reviewedPath, {includeReviewed, checkReviewed});

	let targets;
	if (all) {
		const files = given.length > 0 ? given : git('ls-files', '--', 'src').split('\n');
		targets = new Map(
			files.filter(Boolean).map((file) => [path.relative(APP_DIR, path.resolve(APP_DIR, file)), 'all']),
		);
	} else {
		const changes = forkChanges(upstream);
		targets = given.length > 0 ? new Map(given.map((file) => [file, changes.get(file) ?? new Set()])) : changes;
	}

	const hasReviewedCss = Boolean(catalog?.entries.some((e) => e.linter === 'web-safety' && e.file.endsWith('.css')));
	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		if (!SOURCE_RE.test(file) || SKIPPED_RE.test(file)) continue;
		// Upstream CSS intentionally keeps @media width/height queries in px; only check CSS on fork diffs
		// or when files/rules (or CSS reviewed entries) are passed explicitly.
		if (file.endsWith('.css') && all && given.length === 0 && !explicitRules && !hasReviewedCss) continue;
		const abs = path.join(APP_DIR, file);
		if (fs.existsSync(abs)) {
			problems.push(...lintWebSafetySource(file, fs.readFileSync(abs, 'utf8'), lines, {rules, reviewed: catalog}));
		}
	}

	finishReviewedCheckOrNotes({
		linter: 'web-safety',
		catalog,
		reviewedPath,
		checkReviewed,
		reportAllSummary: all,
		allFilesScanned: given.length === 0,
		rules,
	});

	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} web safety violation(s). Fix the underlying issue, mark fork lines with \`// web-safety-ignore: <reason>\`, or record reviewed upstream entries in \`fluxer_app/scripts/fork-lint-reviewed.json\`.`,
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
