// Fork: finds network/fetch calls inside React render bodies or dependency-less useEffect hooks
// in the fork's web code (tyne-chat/tyne#114, tyne-chat/tyne#945).
//
//   node scripts/fork-render-fetch-lint.mjs [--upstream <git ref>] [--all] [<file>...]
//
// Rules:
// 1. `[render-fetch]`: direct HTTP/REST/store fetch calls (`http.get/post/put/patch/delete/request`,
//    `fetch(...)`, `*Commands.fetch*`, `*Store.fetch*`, `fetchPersonas`, `fetchPersona*`) executed
//    synchronously in a React component or custom hook body (outside `useEffect`, `useLayoutEffect`,
//    event handlers, and non-IIFE callbacks).
// 2. `[effect-no-deps-fetch]`: direct HTTP/REST/store fetch calls inside `useEffect(() => ...)` or
//    `useLayoutEffect(() => ...)` with no dependency array (which re-runs after every render).
//
// Suppress a deliberate exception with `// render-fetch-ignore: <reason>` on its line or the line above.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parse} from '@babel/parser';

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_RE = /^src\/.*\.(ts|tsx|js|jsx|mjs)$/;
const SKIPPED_RE =
	/(\.test\.|\.spec\.|\.stories\.|\.bench\.|\/__tests__\/|\/__fixtures__\/|\/test\/|\/testing\/|\.d\.ts$)/;
const GENERATED_RE = /^\/\/ (Generated by |@generated|GENERATED CODE)/m;
const IGNORE_RE = /render-fetch-ignore:\s*\S/;

const HTTP_OBJECT_RE = /^(http|instanceHttp|restClient|apiClient)$/i;
const HTTP_METHOD_RE = /^(get|post|put|patch|delete|head|request)$/;
const FETCH_METHOD_RE = /^fetch[A-Z]\w*$/;
const EFFECT_HOOK_RE = /^(useEffect|useLayoutEffect)$/;
const COMPONENT_WRAPPER_RE = /^(observer|memo|forwardRef)$/;

function git(...args) {
	return execFileSync('git', args, {cwd: APP_DIR, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	for (const line of git('diff', '-U0', '--no-color', '--no-renames', '--diff-filter=AM', base, '--', 'src').split(
		'\n',
	)) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/fluxer_app/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', 'src').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

function identName(node) {
	if (!node) return undefined;
	if (node.type === 'Identifier') return node.name;
	if (node.type === 'MemberExpression' || node.type === 'OptionalMemberExpression') {
		return identName(node.property);
	}
	return undefined;
}

function rootIdentName(node) {
	let cur = node;
	while (cur && (cur.type === 'MemberExpression' || cur.type === 'OptionalMemberExpression')) {
		cur = cur.object;
	}
	return cur?.type === 'Identifier' ? cur.name : undefined;
}

function describeNetworkCall(callNode) {
	const callee = callNode.callee;
	if (!callee) return undefined;
	if (callee.type === 'Identifier') {
		if (callee.name === 'fetch' || FETCH_METHOD_RE.test(callee.name)) {
			return `${callee.name}()`;
		}
		return undefined;
	}
	if (callee.type === 'MemberExpression' || callee.type === 'OptionalMemberExpression') {
		const obj = rootIdentName(callee);
		const prop = identName(callee.property);
		if (!obj || !prop) return undefined;
		if (HTTP_OBJECT_RE.test(obj) && HTTP_METHOD_RE.test(prop)) {
			return `${obj}.${prop}()`;
		}
		if (FETCH_METHOD_RE.test(prop) && /(Commands|Store|Service|Client|API|Directory)$/.test(obj)) {
			return `${obj}.${prop}()`;
		}
	}
	return undefined;
}

function isReactComponentOrHookName(name) {
	if (!name) return false;
	return /^[A-Z][A-Za-z0-9]*$/.test(name) || /^use[A-Z][A-Za-z0-9]*$/.test(name);
}

function isComponentFunction(fnNode, parent, grandParent) {
	if (fnNode.id?.type === 'Identifier' && isReactComponentOrHookName(fnNode.id.name)) {
		return true;
	}
	if (parent?.type === 'VariableDeclarator' && parent.id?.type === 'Identifier') {
		if (isReactComponentOrHookName(parent.id.name)) return true;
	}
	if (parent?.type === 'CallExpression') {
		const wrapperName = identName(parent.callee);
		if (wrapperName && COMPONENT_WRAPPER_RE.test(wrapperName)) {
			if (grandParent?.type === 'VariableDeclarator' && grandParent.id?.type === 'Identifier') {
				return isReactComponentOrHookName(grandParent.id.name);
			}
			// Nested `observer(forwardRef(...))` or `memo(observer(...))`.
			return true;
		}
	}
	return false;
}

function isEffectCallbackWithoutDeps(fnNode, parent) {
	if (parent?.type !== 'CallExpression') return false;
	if (parent.arguments[0] !== fnNode) return false;
	const hookName = identName(parent.callee);
	if (!hookName || !EFFECT_HOOK_RE.test(hookName)) return false;
	return parent.arguments.length < 2;
}

function isImmediatelyInvoked(fnNode, parent) {
	return (parent?.type === 'CallExpression' || parent?.type === 'OptionalCallExpression') && parent.callee === fnNode;
}

/**
 * Checks a single file's source on the given lines ('all' or Set<number>).
 * @param {string} file
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @returns {Array<string>}
 */
export function lintRenderFetchSource(file, source, lines = 'all') {
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	let ast;
	try {
		ast = parse(source, {sourceType: 'module', plugins: ['typescript', 'jsx', 'decorators'], errorRecovery: true});
	} catch (error) {
		return [`${file}: could not parse: ${error.message}`];
	}
	const ignored = new Set();
	for (const comment of ast.comments ?? []) {
		if (IGNORE_RE.test(comment.value)) {
			ignored.add(comment.loc.end.line);
			ignored.add(comment.loc.end.line + 1);
		}
	}

	const problems = [];
	// Stack of active execution contexts: 'other' | 'render' | 'effect-no-deps'
	const modeStack = ['other'];
	const ancestors = [];

	const visit = (node) => {
		if (!node || typeof node.type !== 'string') return;
		const parent = ancestors.at(-1);
		const grandParent = ancestors.at(-2);

		const isFn =
			node.type === 'FunctionDeclaration' ||
			node.type === 'FunctionExpression' ||
			node.type === 'ArrowFunctionExpression';

		if (isFn) {
			let nextMode = 'other';
			if (isEffectCallbackWithoutDeps(node, parent)) {
				nextMode = 'effect-no-deps';
			} else if (isComponentFunction(node, parent, grandParent)) {
				nextMode = 'render';
			} else if (isImmediatelyInvoked(node, parent)) {
				nextMode = modeStack.at(-1);
			}
			modeStack.push(nextMode);
		}

		if (node.type === 'CallExpression' || node.type === 'OptionalCallExpression') {
			const mode = modeStack.at(-1);
			if (mode === 'render' || mode === 'effect-no-deps') {
				const desc = describeNetworkCall(node);
				const line = node.loc?.start.line;
				if (desc && line && (lines === 'all' || lines.has(line)) && !ignored.has(line)) {
					const col = (node.loc?.start.column ?? 0) + 1;
					if (mode === 'render') {
						problems.push(
							`${file}:${line}:${col}: [render-fetch] network call \`${desc}\` inside React render/hook body (move into useEffect with deps or an event handler; tyne-chat/tyne#114)`,
						);
					} else {
						problems.push(
							`${file}:${line}:${col}: [effect-no-deps-fetch] network call \`${desc}\` inside useEffect without a dependency array (runs after every render; tyne-chat/tyne#114)`,
						);
					}
				}
			}
		}

		ancestors.push(node);
		for (const key of Object.keys(node)) {
			if (key === 'loc' || key === 'leadingComments' || key === 'trailingComments' || key === 'innerComments') continue;
			const value = node[key];
			if (Array.isArray(value)) value.forEach(visit);
			else if (value && typeof value === 'object' && typeof value.type === 'string') visit(value);
		}
		ancestors.pop();

		if (isFn) {
			modeStack.pop();
		}
	};

	visit(ast.program);
	return problems;
}

function optionValue(name, fallback) {
	const index = process.argv.indexOf(name);
	return index === -1 ? fallback : process.argv[index + 1];
}

function main() {
	const all = process.argv.includes('--all');
	const upstream = optionValue('--upstream', 'upstream/main');
	const given = process.argv.slice(2).filter((arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream');
	let targets;
	if (all) {
		const files = given.length > 0 ? given : git('ls-files', '--', 'src').split('\n');
		targets = new Map(files.filter(Boolean).map((file) => [path.relative(APP_DIR, path.resolve(file)), 'all']));
	} else {
		const changes = forkChanges(upstream);
		targets = given.length > 0 ? new Map(given.map((file) => [file, changes.get(file) ?? new Set()])) : changes;
	}
	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		if (SOURCE_RE.test(file) && !SKIPPED_RE.test(file) && fs.existsSync(path.join(APP_DIR, file))) {
			problems.push(...lintRenderFetchSource(file, fs.readFileSync(path.join(APP_DIR, file), 'utf8'), lines));
		}
	}
	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} React render/effect network-call violation(s). Move fetches into a guarded ` +
				'useEffect(..., [deps]) or event handler, or mark with `// render-fetch-ignore: <reason>`.',
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
