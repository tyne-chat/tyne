const GENERATED_RE = /^\/[/*] ?(Generated by |@generated|GENERATED CODE)/m;

const WEB_SAFETY_IGNORE_RE = /web-safety-ignore:\s*\S/;
const SAFETY_IGNORE_RE = /safety-lint-ignore:\s*\S/;
const RENDER_FETCH_IGNORE_RE = /render-fetch-ignore:\s*\S/;
const I18N_IGNORE_RE = /i18n-ignore:\s*\S/;
const PX_OK_RE = /px-ok:\s*\S/;
const FORK_COMMENT_RE = /\/\/\s*Fork:/;
const PX_RE = /(?:(?<![\w.$-])|(?<=(?:^|[\s(,:'"`])-))(\d+(?:\.\d+)?)px\b/g;
const CSS_DECLARATION_RE = /^\s*([a-z-]+)\s*:(.*)$/;

/**
 * Finds positive `Npx` tokens (excluding `0px`) inside a string.
 * @param {string} text
 * @returns {Array<{value: string; label: string; index: number}>}
 */
export function findPositivePxMatches(text) {
	const matches = [];
	for (const match of text.matchAll(PX_RE)) {
		if (Number(match[1]) > 0) {
			matches.push({value: match[1], label: `${match[1]}px`, index: match.index ?? 0});
		}
	}
	return matches;
}

/**
 * Strips block comments across CSS lines while preserving exact line count.
 * @param {ReadonlyArray<string>} lines
 * @returns {Array<string>}
 */
function stripCssComments(lines) {
	let inComment = false;
	return lines.map((line) => {
		let code = '';
		let rest = line;
		while (rest.length > 0) {
			if (inComment) {
				const end = rest.indexOf('*/');
				if (end === -1) return code;
				inComment = false;
				rest = rest.slice(end + 2);
			} else {
				const start = rest.indexOf('/*');
				if (start === -1) return code + rest;
				code += rest.slice(0, start);
				inComment = true;
				rest = rest.slice(start + 2);
			}
		}
		return code;
	});
}

function buildDirectiveTable(sourceLines, astComments = null) {
	const webSafetyIgnored = new Set();
	const safetyIgnored = new Set();
	const renderFetchIgnored = new Set();
	const i18nIgnored = new Set();
	const pxOkLines = new Set();
	const forkCommentPrevLines = new Set();

	const addFromComments = (targetSet, regex) => {
		if (astComments) {
			for (const comment of astComments) {
				if (regex.test(comment.value)) {
					targetSet.add(comment.loc.end.line);
					targetSet.add(comment.loc.end.line + 1);
				}
			}
		} else {
			for (let i = 0; i < sourceLines.length; i++) {
				if (regex.test(sourceLines[i])) {
					targetSet.add(i + 1);
					targetSet.add(i + 2);
				}
			}
		}
	};

	addFromComments(webSafetyIgnored, WEB_SAFETY_IGNORE_RE);
	addFromComments(safetyIgnored, SAFETY_IGNORE_RE);
	addFromComments(renderFetchIgnored, RENDER_FETCH_IGNORE_RE);
	addFromComments(i18nIgnored, I18N_IGNORE_RE);

	for (let i = 0; i < sourceLines.length; i++) {
		const line = sourceLines[i];
		if (PX_OK_RE.test(line)) {
			pxOkLines.add(i + 1);
			pxOkLines.add(i + 2);
		}
		if (FORK_COMMENT_RE.test(line)) {
			forkCommentPrevLines.add(i + 2);
		}
	}

	return {
		webSafetyIgnored,
		safetyIgnored,
		renderFetchIgnored,
		i18nIgnored,
		pxOkLines,
		forkCommentPrevLines,
	};
}

/**
 * Shared CSS stylesheet IR consumed by both `px` and `web-safety` (`zoom-blind-viewport`).
 * @param {SourceUnit} unit
 */
function buildCssStylesheetIR(unit) {
	const {sourceLines} = unit;
	const codeLines = stripCssComments(sourceLines);
	const entries = [];
	let depth = 0;
	let markedRuleDepth = null;

	for (let i = 0; i < codeLines.length; i++) {
		const line = i + 1;
		const code = codeLines[i];
		const rawLine = sourceLines[i];
		const prevRawLine = i > 0 ? sourceLines[i - 1] : '';

		const opens = (code.match(/\{/g) ?? []).length;
		const closes = (code.match(/\}/g) ?? []).length;
		const pxMarked = PX_OK_RE.test(rawLine) || PX_OK_RE.test(prevRawLine);
		if (markedRuleDepth === null && opens > 0 && pxMarked) {
			markedRuleDepth = depth;
		}
		const inMarkedPxOkRule = markedRuleDepth !== null;
		depth += opens - closes;
		if (markedRuleDepth !== null && depth <= markedRuleDepth) {
			markedRuleDepth = null;
		}

		const isMediaQuery = /^\s*@media\b/.test(code);
		const declaration = CSS_DECLARATION_RE.exec(code);

		entries.push({
			line,
			code,
			rawLine,
			trimmedRaw: rawLine.trim(),
			inMarkedPxOkRule,
			isMediaQuery,
			declProperty: declaration ? declaration[1] : null,
		});
	}

	return {entries};
}

function maskRustSource(source) {
	const testCut = source.search(/#\[\s*cfg\s*\(\s*test\s*\)\s*\]/);
	const prod = testCut === -1 ? source : source.slice(0, testCut);
	const chars = prod.split('');
	let i = 0;
	while (i < chars.length) {
		const c = chars[i];
		const next = chars[i + 1];
		if (c === '/' && next === '/') {
			while (i < chars.length && chars[i] !== '\n') chars[i++] = ' ';
		} else if (c === '/' && next === '*') {
			chars[i++] = ' ';
			chars[i++] = ' ';
			let depth = 1;
			while (i < chars.length && depth > 0) {
				if (chars[i] === '/' && chars[i + 1] === '*') {
					chars[i++] = ' ';
					chars[i++] = ' ';
					depth++;
				} else if (chars[i] === '*' && chars[i + 1] === '/') {
					chars[i++] = ' ';
					chars[i++] = ' ';
					depth--;
				} else {
					if (chars[i] !== '\n') chars[i] = ' ';
					i++;
				}
			}
		} else if (c === '"') {
			chars[i++] = ' ';
			while (i < chars.length && chars[i] !== '"') {
				if (chars[i] === '\\' && i + 1 < chars.length) {
					if (chars[i + 1] !== '\n') chars[i + 1] = ' ';
					chars[i++] = ' ';
				}
				if (chars[i] !== '\n') chars[i] = ' ';
				i++;
			}
			if (i < chars.length) chars[i++] = ' ';
		} else {
			i++;
		}
	}
	return chars.join('');
}

function maskGleamSource(source) {
	const chars = source.split('');
	let i = 0;
	while (i < chars.length) {
		if (chars[i] === '/' && chars[i + 1] === '/') {
			while (i < chars.length && chars[i] !== '\n') chars[i++] = ' ';
		} else if (chars[i] === '"') {
			chars[i++] = ' ';
			while (i < chars.length && chars[i] !== '"') {
				if (chars[i] === '\\' && i + 1 < chars.length) {
					if (chars[i + 1] !== '\n') chars[i + 1] = ' ';
					chars[i++] = ' ';
				}
				if (chars[i] !== '\n') chars[i] = ' ';
				i++;
			}
			if (i < chars.length) chars[i++] = ' ';
		} else {
			i++;
		}
	}
	return chars.join('');
}

function extractBracedCallables(masked, headerRe, stopAtSemicolon) {
	const callables = [];
	for (const m of masked.matchAll(headerRe)) {
		const name = m[1];
		let idx = m.index + m[0].length;
		let bodyStart = -1;
		while (idx < masked.length) {
			if (stopAtSemicolon && masked[idx] === ';') break;
			if (masked[idx] === '{') {
				bodyStart = idx;
				break;
			}
			idx++;
		}
		if (bodyStart === -1) continue;
		let depth = 1;
		let p = bodyStart + 1;
		while (p < masked.length && depth > 0) {
			if (masked[p] === '{') depth++;
			else if (masked[p] === '}') depth--;
			p++;
		}
		callables.push({
			name,
			bodyStart,
			bodyEnd: p,
			bodyMasked: masked.slice(bodyStart, p),
		});
	}
	return callables;
}

/**
 * Masks comments/strings and extracts braced callable bodies for Rust or Gleam sources.
 * @param {SourceUnit} unit
 * @param {'rust' | 'gleam'} kind
 */
function buildMaskedBracedIR(unit, kind) {
	const masked = kind === 'rust' ? maskRustSource(unit.source) : maskGleamSource(unit.source);
	const headerRe =
		kind === 'rust' ? /\basync\s+fn\s+([A-Za-z_][A-Za-z0-9_]*)\b/g : /\bpub\s+fn\s+([a-zA-Z0-9_]+_test)\s*\(/g;
	const callables = extractBracedCallables(masked, headerRe, kind === 'rust');
	return {kind, masked, callables};
}

/**
 * @typedef {ReturnType<typeof createSourceUnit>} SourceUnit
 */

/**
 * Creates a Stage 2 `SourceUnit` wrapping file metadata, source text, lazy line/column lookup,
 * directive suppression tables, CSS stylesheet IR, and masked Rust/Gleam braced IR.
 * @param {{
 *   repoFile: string;
 *   displayFile: string;
 *   source: string;
 *   lines?: 'all' | Set<number>;
 * }} params
 */
export function createSourceUnit({repoFile, displayFile, source, lines = 'all'}) {
	const normalizedDisplay = displayFile.replace(/\\/g, '/');
	const normalizedRepo = repoFile.replace(/\\/g, '/');
	const isGenerated = GENERATED_RE.test(source.slice(0, 500));
	const sourceLines = isGenerated ? [] : source.split('\n');
	let lineStarts = null;
	let directivesNoComments = null;
	let directivesWithComments = null;
	let cssIR = null;
	const maskedIRs = new Map();

	const computeLineStarts = () => {
		if (!lineStarts) {
			lineStarts = [0];
			for (let i = 0; i < source.length; i++) {
				if (source[i] === '\n') lineStarts.push(i + 1);
			}
		}
		return lineStarts;
	};

	const lineColOf = (offset) => {
		const starts = computeLineStarts();
		let low = 0;
		let high = starts.length - 1;
		while (low < high) {
			const mid = Math.ceil((low + high) / 2);
			if (starts[mid] <= offset) low = mid;
			else high = mid - 1;
		}
		return {line: low + 1, col: offset - starts[low] + 1};
	};

	const unit = {
		repoFile: normalizedRepo,
		displayFile: normalizedDisplay,
		source,
		sourceLines,
		lines,
		isGenerated,
		isLineEnabled(line) {
			return Boolean(line && (lines === 'all' || lines.has(line)));
		},
		lineColOf,
		sourceLineAt(line) {
			return line >= 1 && line <= sourceLines.length ? sourceLines[line - 1] : '';
		},
		getDirectives(astComments = null) {
			if (astComments) {
				if (!directivesWithComments) {
					directivesWithComments = buildDirectiveTable(sourceLines, astComments);
				}
				return directivesWithComments;
			}
			if (!directivesNoComments) {
				directivesNoComments = buildDirectiveTable(sourceLines, null);
			}
			return directivesNoComments;
		},
		getCssIR() {
			if (!cssIR) cssIR = buildCssStylesheetIR(unit);
			return cssIR;
		},
		getMaskedIR(kind) {
			if (!maskedIRs.has(kind)) maskedIRs.set(kind, buildMaskedBracedIR(unit, kind));
			return maskedIRs.get(kind);
		},
	};
	return unit;
}
