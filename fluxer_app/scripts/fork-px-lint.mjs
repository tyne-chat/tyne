// Fork: finds sizes in px in the fork's web code (tyne-chat/tyne#637). The desktop app zooms by the root
// font size (`--custom-zoom`, src/app/globals.css), so rem sizes grow with the zoom and px sizes do not;
// a px cap around rem content hid the bottom of the autocomplete list (tyne-chat/tyne#636).
//
//   node scripts/fork-px-lint.mjs [--upstream <git ref>] [--all] [<file>...]
//       Report px sizes above 1px (and below 999px, a pill's radius): in CSS declarations (border widths,
//       outlines and shadows excepted, at-rules such as @media skipped), and in scripts as string literals
//       ('12px', 'calc(100% - 8px)', '(max-height: 680px)') and as bare numbers for size keys inside style
//       objects ({width: 16}). Values computed from a measurement (`${rect.height}px`) are not reported.
//       Only files the fork added and lines it changed against the merge base with <git ref> (default
//       upstream/main) are checked, working tree and untracked files included; --all checks every line of
//       the files given (or of every source file). A px value that really belongs in screen pixels (a
//       pointer hit zone, an observer's margin) gets `px-ok: <reason>` in a comment on its line or the line
//       above.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_RE = /^src\/.*\.(css|ts|tsx|js|jsx|mjs)$/;
const SKIPPED_RE =
	/(\.test\.|\.spec\.|\.stories\.|\.bench\.|\/__tests__\/|\/__fixtures__\/|\/test\/|\/testing\/|\.d\.ts$)/;
const GENERATED_RE = /^\/[/*] ?(Generated by |@generated|GENERATED CODE)/m;
const IGNORE_RE = /px-ok:\s*\S/;

const PX_RE = /(?<![\w.$-])(\d+(?:\.\d+)?)px\b/g;
const CSS_DECLARATION_RE = /^\s*([a-z-]+)\s*:(.*)$/;
// Inside a string literal ('…', "…" or a template's text) of a script.
const STRING_RE = /'(?:[^'\\\n]|\\.)*'|"(?:[^"\\\n]|\\.)*"|`(?:[^`\\]|\\.)*`/g;
const STYLE_KEY_RE =
	/\b(width|height|minWidth|maxWidth|minHeight|maxHeight|top|right|bottom|left|inset|margin\w*|padding\w*|gap|rowGap|columnGap|fontSize|lineHeight|borderRadius|flexBasis)\s*:\s*(\d+(?:\.\d+)?)\s*(?=[,}]|$)/g;

function git(...args) {
	return execFileSync('git', args, {cwd: APP_DIR, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	for (const line of git('diff', '-U0', '--no-color', '--no-renames', '--diff-filter=AM', base, '--', 'src').split(
		'\n',
	)) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/fluxer_app/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', 'src').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

function sizesAboveOnePx(text) {
	return (
		[...text.matchAll(PX_RE)]
			.map((match) => Number(match[1]))
			// 999px and up is a pill's radius, the same at every size.
			.filter((value) => value > 1 && value < 999)
			.map((value) => `${value}px`)
	);
}

// Lines inside style objects (`style={{…}}`, `style: {…}`, `Object.assign(element.style, {…})`): only there
// is a bare number a size in px. Elsewhere it is often in screen px on purpose (Floating UI's `padding`).
function styleObjectLines(source) {
	const lines = new Set();
	for (const match of source.matchAll(/style=\{\{|\bstyle:\s*\{|\.style,\s*\{/g)) {
		let index = match.index + match[0].length - 1;
		let depth = 0;
		const startLine = source.slice(0, index).split('\n').length;
		for (; index < source.length; index++) {
			if (source[index] === '{') depth++;
			else if (source[index] === '}' && --depth === 0) break;
		}
		const endLine = source.slice(0, index).split('\n').length;
		for (let line = startLine; line <= endLine; line++) lines.add(line);
	}
	return lines;
}

function cssProblems(line) {
	const trimmed = line.trim();
	if (trimmed.startsWith('@') || trimmed.startsWith('/*') || trimmed.startsWith('*')) return [];
	const declaration = CSS_DECLARATION_RE.exec(line);
	if (!declaration) return [];
	const property = declaration[1];
	if ((property.startsWith('border') && !property.includes('radius')) || property.startsWith('outline')) return [];
	if (property.includes('shadow')) return [];
	return sizesAboveOnePx(declaration[2]).map((size) => `${property}: ${size}`);
}

function scriptProblems(line, inStyleObject) {
	const code = line.replace(/\/\/.*$/, '');
	const problems = [];
	for (const literal of code.match(STRING_RE) ?? []) {
		// A template's ${…} parts are computed; only its text is a literal.
		const text = literal.startsWith('`') ? literal.replace(/\$\{[^}]*\}(px)?/g, '') : literal;
		for (const size of sizesAboveOnePx(text)) problems.push(`literal ${size}`);
	}
	if (inStyleObject) {
		for (const match of code.matchAll(STYLE_KEY_RE)) {
			if (Number(match[2]) > 1) problems.push(`${match[1]}: ${match[2]} (px)`);
		}
	}
	return problems;
}

/**
 * The problems in one file's source, on the given lines ('all' for every line).
 * @param {string} file
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @returns {Array<string>}
 */
export function lintSource(file, source, lines = 'all') {
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	const css = file.endsWith('.css');
	const sourceLines = source.split('\n');
	const styleLines = css ? new Set() : styleObjectLines(source);
	const problems = [];
	sourceLines.forEach((text, index) => {
		const line = index + 1;
		if (lines !== 'all' && !lines.has(line)) return;
		if (IGNORE_RE.test(text) || (index > 0 && IGNORE_RE.test(sourceLines[index - 1]))) return;
		for (const problem of css ? cssProblems(text) : scriptProblems(text, styleLines.has(line))) {
			problems.push(`${file}:${line}: ${problem}`);
		}
	});
	return problems;
}

function optionValue(name, fallback) {
	const index = process.argv.indexOf(name);
	return index === -1 ? fallback : process.argv[index + 1];
}

function main() {
	const all = process.argv.includes('--all');
	const upstream = optionValue('--upstream', 'upstream/main');
	const given = process.argv.slice(2).filter((arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream');
	let targets;
	if (all) {
		const files = given.length > 0 ? given : git('ls-files', '--', 'src').split('\n');
		targets = new Map(files.filter(Boolean).map((file) => [path.relative(APP_DIR, path.resolve(file)), 'all']));
	} else {
		const changes = forkChanges(upstream);
		targets = given.length > 0 ? new Map(given.map((file) => [file, changes.get(file) ?? new Set()])) : changes;
	}
	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		if (SOURCE_RE.test(file) && !SKIPPED_RE.test(file) && fs.existsSync(path.join(APP_DIR, file))) {
			problems.push(...lintSource(file, fs.readFileSync(path.join(APP_DIR, file), 'utf8'), lines));
		}
	}
	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} size(s) in px. Use rem (16px = 1rem), which follows the desktop app's zoom, ` +
				'or mark a value that belongs in screen pixels `px-ok: <reason>`.',
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
