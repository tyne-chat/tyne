// Fork: finds sizes in px in the fork's web code, which upstream writes in rem (tyne-chat/tyne#637). The
// desktop app zooms by the root font size (`--custom-zoom`, src/app/globals.css), so rem sizes grow with
// the zoom and px sizes do not; a px cap around rem content hid the bottom of the autocomplete list
// (tyne-chat/tyne#636).
//
//   node scripts/fork-px-lint.mjs [--upstream <git ref>] [--all] [<file>...]
//       Report every px size other than 0px: in CSS outside comments and @media queries (borders,
//       shadows, outlines and radii included, as upstream writes them in rem), and in scripts as string
//       literals ('1px', 'calc(100% - 8px)', '(max-height: 680px)') and as bare numbers for size keys
//       inside style objects ({width: 16}). Values computed from a measurement (`${rect.height}px`) are not
//       reported. Only files the fork added and lines it changed against the merge base with <git ref>
//       (default upstream/main) are checked, working tree and untracked files included; --all checks every
//       line of the files given (or of every source file). A px value where upstream keeps px too (an
//       IntersectionObserver's rootMargin, which takes no rem), or a size about device pixels, gets
//       `px-ok: <reason>` in a comment on its line or the line above; above a CSS rule, for the whole rule.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_RE = /^src\/.*\.(css|ts|tsx|js|jsx|mjs)$/;
const SKIPPED_RE =
	/(\.test\.|\.spec\.|\.stories\.|\.bench\.|\/__tests__\/|\/__fixtures__\/|\/test\/|\/testing\/|\.d\.ts$)/;
const GENERATED_RE = /^\/[/*] ?(Generated by |@generated|GENERATED CODE)/m;
const IGNORE_RE = /px-ok:\s*\S/;

// A number not inside a name (`--gap-4px`), with its minus sign when it has one (`-4px`, '-4px').
const PX_RE = /(?:(?<![\w.$-])|(?<=(?:^|[\s(,:'"`])-))(\d+(?:\.\d+)?)px\b/g;
const CSS_DECLARATION_RE = /^\s*([a-z-]+)\s*:(.*)$/;
// Keys whose bare number React renders in px (a bare lineHeight is a multiplier).
const STYLE_KEY_RE =
	/\b(width|height|(?:min|max)(?:Width|Height|InlineSize|BlockSize)|inlineSize|blockSize|top|right|bottom|left|inset\w*|margin\w*|padding\w*|gap|rowGap|columnGap|fontSize|letterSpacing|textIndent|border\w*Radius|border\w*Width|outlineWidth|outlineOffset|flexBasis)\s*:/g;

function git(...args) {
	return execFileSync('git', args, {cwd: APP_DIR, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	for (const line of git('diff', '-U0', '--no-color', '--no-renames', '--diff-filter=AM', base, '--', 'src').split(
		'\n',
	)) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/fluxer_app/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', 'src').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

// 0px is the same at every zoom.
function pxSizes(text) {
	return [...text.matchAll(PX_RE)].filter((match) => Number(match[1]) > 0).map((match) => `${match[1]}px`);
}

// A line of CSS with its comments taken out. Upstream writes its @media queries in px, and no unit makes
// one follow the zoom (rem in a media query is the browser's 16px): a layout switch that must follow it is
// an @container query in rem, which this checks.
function cssProblems(code) {
	if (/^\s*@media\b/.test(code)) return [];
	const declaration = CSS_DECLARATION_RE.exec(code);
	return pxSizes(code).map((size) => (declaration ? `${declaration[1]}: ${size}` : size));
}

// Whether a `/` at this point of the code starts a regular expression rather than a division.
function startsRegExp(code, index) {
	let k = index - 1;
	while (k >= 0 && /\s/.test(code[k])) k--;
	if (k < 0 || /[(,=:[!&|?{;+\-*%~^]/.test(code[k])) return true;
	if (code[k] === '>' && code[k - 1] === '=') return true;
	return /\b(return|typeof|case|in|of|new|delete|void|throw)$/.test(code.slice(Math.max(0, k - 9), k + 1).join(''));
}

// The script with its strings, comments and regular expressions blanked (line breaks kept), and the text of
// each string: a template's text without its ${…} parts, which are code. A quote or a backtick does not
// span lines unless it opens a template.
function scanScript(source) {
	const code = source.split('');
	const strings = [];
	const templateDepths = [];
	let depth = 0;
	const blank = (from, to) => {
		for (let k = from; k < to && k < code.length; k++) if (code[k] !== '\n') code[k] = ' ';
	};
	let i = 0;
	while (i < source.length) {
		const c = source[i];
		if (c === '/' && source[i + 1] === '/') {
			const end = source.indexOf('\n', i);
			const stop = end === -1 ? source.length : end;
			blank(i, stop);
			i = stop;
		} else if (c === '/' && source[i + 1] === '*') {
			const end = source.indexOf('*/', i + 2);
			const stop = end === -1 ? source.length : end + 2;
			blank(i, stop);
			i = stop;
		} else if (c === '/' && startsRegExp(code, i)) {
			let j = i + 1;
			let inClass = false;
			while (j < source.length && source[j] !== '\n' && (inClass || source[j] !== '/')) {
				if (source[j] === '\\') j++;
				else if (source[j] === '[') inClass = true;
				else if (source[j] === ']') inClass = false;
				j++;
			}
			blank(i, j + 1);
			i = j + 1;
		} else if (c === "'" || c === '"') {
			let j = i + 1;
			while (j < source.length && source[j] !== c && source[j] !== '\n') j += source[j] === '\\' ? 2 : 1;
			strings.push({start: i + 1, text: source.slice(i + 1, j)});
			blank(i, j + 1);
			i = j + 1;
		} else if (c === '`' || (c === '}' && templateDepths.at(-1) === depth)) {
			if (c === '}') templateDepths.pop();
			let j = i + 1;
			while (j < source.length && source[j] !== '`' && !(source[j] === '$' && source[j + 1] === '{')) {
				j += source[j] === '\\' ? 2 : 1;
			}
			strings.push({start: i + 1, text: source.slice(i + 1, j)});
			const opensCode = source[j] === '$';
			blank(i, j + (opensCode ? 2 : 1));
			if (opensCode) templateDepths.push(depth);
			i = j + (opensCode ? 2 : 1);
		} else {
			if (c === '{') depth++;
			else if (c === '}') depth--;
			i++;
		}
	}
	return {code, strings};
}

// Style objects (`style={{…}}`, `style: {…}`, `Object.assign(element.style, {…})`) as [first, last] offsets:
// only there is a bare number a size in px. Elsewhere it is often in screen px on purpose (Floating UI).
function styleObjectRanges(code) {
	const text = code.join('');
	const ranges = [];
	for (const match of text.matchAll(/style=\{\{|\bstyle:\s*\{|\.style,\s*\{/g)) {
		const first = match.index + match[0].length - 1;
		let index = first;
		let depth = 0;
		for (; index < code.length; index++) {
			if (code[index] === '{') depth++;
			else if (code[index] === '}' && --depth === 0) break;
		}
		ranges.push([first, index]);
	}
	return ranges;
}

// The bare numbers in a style object's size values, outside any call or bracket (remFromPx(2) and
// Math.max(…) are left alone), with their offsets: `tagError ? 2 : 0` and `-2` are px.
function styleNumbers(code, [first, last]) {
	const found = [];
	const body = code.slice(first, last + 1).join('');
	for (const key of body.matchAll(STYLE_KEY_RE)) {
		let depth = 0;
		for (let k = first + key.index + key[0].length; k < last; k++) {
			const ch = code[k];
			if ('([{'.includes(ch)) depth++;
			else if (')]}'.includes(ch)) {
				if (depth === 0) break;
				depth--;
			} else if (ch === ',' && depth === 0) break;
			else if (depth === 0 && /\d/.test(ch) && !/[\w.$]/.test(code[k - 1] ?? '')) {
				const number = /^\d+(?:\.\d+)?/.exec(code.slice(k, k + 24).join(''))[0];
				if (!/[\w.%]/.test(code[k + number.length] ?? '') && Number(number) > 0) {
					found.push({offset: k, problem: `${key[1]}: ${number} (px)`});
				}
				k += number.length - 1;
			}
		}
	}
	return found;
}

function scriptProblems(source) {
	const {code, strings} = scanScript(source);
	const found = [];
	for (const {start, text} of strings) {
		for (const match of text.matchAll(PX_RE)) {
			if (Number(match[1]) > 0) found.push({offset: start + match.index, problem: `literal ${match[1]}px`});
		}
	}
	for (const range of styleObjectRanges(code)) found.push(...styleNumbers(code, range));
	return found.sort((a, b) => a.offset - b.offset);
}

// Each line of a stylesheet without its comments, which may span lines.
function cssCodeLines(lines) {
	let inComment = false;
	return lines.map((line) => {
		let code = '';
		let rest = line;
		while (rest.length > 0) {
			if (inComment) {
				const end = rest.indexOf('*/');
				if (end === -1) return code;
				inComment = false;
				rest = rest.slice(end + 2);
			} else {
				const start = rest.indexOf('/*');
				if (start === -1) return code + rest;
				code += rest.slice(0, start);
				inComment = true;
				rest = rest.slice(start + 2);
			}
		}
		return code;
	});
}

/**
 * The problems in one file's source, on the given lines ('all' for every line).
 * @param {string} file
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @returns {Array<string>}
 */
export function lintSource(file, source, lines = 'all') {
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	const sourceLines = source.split('\n');
	const reported = (line) =>
		(lines === 'all' || lines.has(line)) &&
		!IGNORE_RE.test(sourceLines[line - 1]) &&
		!(line > 1 && IGNORE_RE.test(sourceLines[line - 2]));
	const problems = [];
	if (file.endsWith('.css')) {
		// A px-ok comment on a rule's first line, or the line above it, covers the whole rule.
		let depth = 0;
		let markedRuleDepth = null;
		cssCodeLines(sourceLines).forEach((code, index) => {
			const opens = (code.match(/\{/g) ?? []).length;
			const closes = (code.match(/\}/g) ?? []).length;
			const marked = IGNORE_RE.test(sourceLines[index]) || (index > 0 && IGNORE_RE.test(sourceLines[index - 1]));
			if (markedRuleDepth === null && opens > 0 && marked) markedRuleDepth = depth;
			const inMarkedRule = markedRuleDepth !== null;
			depth += opens - closes;
			if (markedRuleDepth !== null && depth <= markedRuleDepth) markedRuleDepth = null;
			if (inMarkedRule || !reported(index + 1)) return;
			for (const problem of cssProblems(code)) problems.push(`${file}:${index + 1}: ${problem}`);
		});
		return problems;
	}
	const lineStarts = [0];
	for (let i = 0; i < source.length; i++) if (source[i] === '\n') lineStarts.push(i + 1);
	const lineOf = (offset) => {
		let low = 0;
		let high = lineStarts.length - 1;
		while (low < high) {
			const middle = Math.ceil((low + high) / 2);
			if (lineStarts[middle] <= offset) low = middle;
			else high = middle - 1;
		}
		return low + 1;
	};
	for (const {offset, problem} of scriptProblems(source)) {
		const line = lineOf(offset);
		if (reported(line)) problems.push(`${file}:${line}: ${problem}`);
	}
	return problems;
}

function optionValue(name, fallback) {
	const index = process.argv.indexOf(name);
	return index === -1 ? fallback : process.argv[index + 1];
}

function main() {
	const all = process.argv.includes('--all');
	const upstream = optionValue('--upstream', 'upstream/main');
	// Files given on the command line, as paths relative to fluxer_app (./src/…, or absolute, works too).
	const given = process.argv
		.slice(2)
		.filter((arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream')
		.map((file) => path.relative(APP_DIR, path.resolve(file)));
	let targets;
	if (all) {
		const files = given.length > 0 ? given : git('ls-files', '--', 'src').split('\n').filter(Boolean);
		targets = new Map(files.map((file) => [file, 'all']));
	} else {
		const changes = forkChanges(upstream);
		targets = given.length > 0 ? new Map(given.map((file) => [file, changes.get(file) ?? new Set()])) : changes;
	}
	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		if (SOURCE_RE.test(file) && !SKIPPED_RE.test(file) && fs.existsSync(path.join(APP_DIR, file))) {
			problems.push(...lintSource(file, fs.readFileSync(path.join(APP_DIR, file), 'utf8'), lines));
		}
	}
	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} size(s) in px. Write them as upstream does, in rem (16px = 1rem; remFromPx(n) in ` +
				'style objects; var(--radius-full) for a pill), which follows the desktop zoom. See CHECKS.md.',
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
