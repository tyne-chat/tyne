// Fork: finds hard-coded user-facing strings in the fork's code, which fork-i18n.mjs cannot see
// because they never reach a catalogue (tyne-chat/tyne#184).
//
//   node scripts/fork-string-lint.mjs [--upstream <git ref>] [--all] [<file>...]
//       Report string literals in places users read them (JSX text, user-facing props and object
//       keys, toasts) that are not wrapped in msg, t, <Trans> or i18n._. Only files the fork added
//       and lines it changed against the merge base with <git ref> (default upstream/main) are
//       checked, working tree and untracked files included; --all checks every line of the files
//       given (or of every source file). A literal that really is not to be translated gets
//       `// i18n-ignore: <reason>` on its line or the line above (or above the statement,
//       declaration, property or prop it is part of).

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parse} from '@babel/parser';

const APP_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_RE = /^src\/.*\.(ts|tsx|js|jsx|mjs)$/;
const SKIPPED_RE =
	/(\.test\.|\.spec\.|\.stories\.|\.bench\.|\/__tests__\/|\/__fixtures__\/|\/test\/|\/testing\/|\.d\.ts$)/;
const GENERATED_RE = /^\/\/ (Generated by |@generated|GENERATED CODE)/m;
const IGNORE_RE = /i18n-ignore:\s*\S/;

// Props and object keys whose value is shown to people.
const UI_NAME_RE =
	/^(children|title|subtitle|label|placeholder|alt|description|tooltip|text|caption|heading|hint|helperText|emptyText|displayName|aria-label|aria-description|aria-valuetext|aria-roledescription|aria-placeholder)$|(Label|Title|Text|Message|Msg|Description|Placeholder|Tooltip|Hint|Caption|Heading)$/;
// Names that look like the above but are for logs and diagnostics.
const NOT_UI_NAME_RE = /^(debug|log|diagnostic|persistFailure)/;
// Calls whose argument is shown to people.
const UI_CALL_RE =
	/^(toast|alert|confirm|prompt|announce|createSystemMessage|setError|set\w*(Error|Message|Text|Label|Title|Status))$/;
const TOAST_OBJECT_RE = /^(Toast|toast)\w*$/;
const TOAST_METHOD_RE = /^(error|success|info|warning|warn|show|message)$/;
// Callees whose arguments are translated already, or never shown.
const TRANSLATED_CALL_RE = /^(msg|t|defineMessage|plural|select|selectOrdinal|_)$/;
const NOT_SHOWN_OBJECT_RE = /^(console|logger|log|Logger|LOG|Sentry)$/;
const TRANSLATED_ELEMENTS = new Set(['Trans', 'Plural', 'Select', 'SelectOrdinal']);
// Parents a literal passes through on its way to where it is used.
const TRANSPARENT = new Set([
	'ConditionalExpression',
	'LogicalExpression',
	'BinaryExpression',
	'TSAsExpression',
	'TSSatisfiesExpression',
	'TSNonNullExpression',
	'ParenthesizedExpression',
	'TemplateLiteral',
	'ArrayExpression',
	'SequenceExpression',
]);

function isUiName(name) {
	return UI_NAME_RE.test(name) && !NOT_UI_NAME_RE.test(name);
}

function git(...args) {
	return execFileSync('git', args, {cwd: APP_DIR, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024});
}

function forkChanges(upstream) {
	const base = git('merge-base', 'HEAD', upstream).trim();
	const changes = new Map();
	let current;
	for (const line of git('diff', '-U0', '--no-color', '--no-renames', '--diff-filter=AM', base, '--', 'src').split(
		'\n',
	)) {
		if (line.startsWith('+++ ')) {
			current = line === '+++ /dev/null' ? undefined : line.slice('+++ b/fluxer_app/'.length);
			if (current) changes.set(current, new Set());
		} else if (current && line.startsWith('@@')) {
			const match = /\+(\d+)(?:,(\d+))?/.exec(line);
			const start = Number(match[1]);
			const count = match[2] === undefined ? 1 : Number(match[2]);
			for (let i = 0; i < count; i++) changes.get(current).add(start + i);
		}
	}
	for (const file of git('ls-files', '--others', '--exclude-standard', '--', 'src').split('\n')) {
		if (file) changes.set(file, 'all');
	}
	return changes;
}

function nameOf(node) {
	if (!node) return undefined;
	if (node.type === 'Identifier' || node.type === 'JSXIdentifier') return node.name;
	if (node.type === 'StringLiteral') return node.value;
	if (node.type === 'JSXNamespacedName') return `${node.namespace.name}:${node.name.name}`;
	if (node.type === 'MemberExpression' || node.type === 'JSXMemberExpression') return nameOf(node.property);
	return undefined;
}

function rootObjectOf(node) {
	while (node && (node.type === 'MemberExpression' || node.type === 'OptionalMemberExpression')) node = node.object;
	return nameOf(node);
}

function textOf(node) {
	if (node.type === 'StringLiteral') return node.value;
	if (node.type === 'JSXText') return node.value;
	return node.quasis.map((quasi) => quasi.value.cooked ?? '').join('');
}

function looksLikeProse(text) {
	const trimmed = text.trim();
	if (!/\p{L}{2,}/u.test(trimmed)) return false;
	if (/^(https?:|mailto:|\/|#|\.)/.test(trimmed)) return false;
	// A CamelCase identifier such as a component name.
	if (/^\p{Lu}\p{Ll}+(\p{Lu}\p{Ll}*)+$/u.test(trimmed)) return false;
	return /\s/.test(trimmed) || /^\p{Lu}\p{Ll}/u.test(trimmed);
}

// The first line of the statement, declaration, property or prop a literal belongs to, so that an
// i18n-ignore comment above a wrapped one covers the literal. Only one that starts at most three
// lines above the literal counts: a comment above a long statement does not cover all of it.
function holderLine(ancestors, line) {
	for (let index = ancestors.length - 1; index >= 0; index--) {
		const node = ancestors[index];
		if (
			/(Statement|Declaration|Declarator)$/.test(node.type) ||
			['ObjectProperty', 'JSXAttribute', 'ClassProperty'].includes(node.type)
		) {
			return line - node.loc.start.line <= 3 ? node.loc.start.line : -1;
		}
	}
	return -1;
}

// Whether a literal is translated already, or sits somewhere nobody reads it.
function isExcluded(ancestors) {
	for (const [index, node] of ancestors.entries()) {
		if (node.type === 'JSXElement' && TRANSLATED_ELEMENTS.has(nameOf(node.openingElement.name))) {
			// <Trans> translates its text and {'text'}, but any other expression inside it is a
			// placeholder, inserted as is: {label ?? 'items'} is not translated.
			const containers = ancestors.slice(index + 1).filter((inner) => inner.type === 'JSXExpressionContainer');
			if (containers.length === 0) return true;
			if (containers.length === 1 && ancestors.at(-1) === containers[0]) return true;
			continue;
		}
		if (node.type === 'TaggedTemplateExpression') return true;
		if (node.type === 'CallExpression' || node.type === 'NewExpression' || node.type === 'OptionalCallExpression') {
			const callee = nameOf(node.callee);
			if (TRANSLATED_CALL_RE.test(callee ?? '')) return true;
			if (NOT_SHOWN_OBJECT_RE.test(rootObjectOf(node.callee) ?? '')) return true;
			if (node.type === 'NewExpression' && /Error$/.test(callee ?? '')) return true;
		}
		if (node.type === 'TSLiteralType' || node.type === 'TSEnumMember' || node.type === 'ImportDeclaration') return true;
	}
	return false;
}

// Where a literal ends up: a description of the place users read it, or undefined.
function sinkOf(literal, ancestors) {
	let child = literal;
	let index = ancestors.length - 1;
	while (index >= 0 && TRANSPARENT.has(ancestors[index].type)) {
		const parent = ancestors[index];
		// A literal used as a condition or compared with something is not shown.
		if (parent.type === 'ConditionalExpression' && parent.test === child) return undefined;
		if (parent.type === 'BinaryExpression' && parent.operator !== '+') return undefined;
		child = parent;
		index--;
	}
	const parent = ancestors[index];
	if (!parent) return undefined;
	const loose = literal.type === 'JSXText' || child !== literal;
	switch (parent.type) {
		case 'JSXElement':
		case 'JSXFragment':
			return 'JSX text';
		case 'JSXExpressionContainer': {
			const holder = ancestors[index - 1];
			if (holder?.type === 'JSXElement' || holder?.type === 'JSXFragment') return 'JSX child';
			if (holder?.type === 'JSXAttribute' && isUiName(nameOf(holder.name) ?? '')) {
				return `prop ${nameOf(holder.name)}`;
			}
			return undefined;
		}
		case 'JSXAttribute':
			return isUiName(nameOf(parent.name) ?? '') && (loose || looksLikeProse(textOf(literal)))
				? `prop ${nameOf(parent.name)}`
				: undefined;
		case 'VariableDeclarator':
			return parent.init === child && isUiName(nameOf(parent.id) ?? '') ? `variable ${nameOf(parent.id)}` : undefined;
		case 'AssignmentExpression':
			return parent.right === child && parent.left.type === 'Identifier' && isUiName(parent.left.name)
				? `variable ${nameOf(parent.left)}`
				: undefined;
		case 'ObjectProperty':
			if (parent.value !== child || parent.computed) return undefined;
			return isUiName(nameOf(parent.key) ?? '') ? `key ${nameOf(parent.key)}` : undefined;
		case 'CallExpression':
		case 'OptionalCallExpression': {
			if (!parent.arguments.includes(child)) return undefined;
			const callee = nameOf(parent.callee) ?? '';
			if (UI_CALL_RE.test(callee)) return `${callee}()`;
			if (TOAST_METHOD_RE.test(callee) && TOAST_OBJECT_RE.test(rootObjectOf(parent.callee) ?? '')) {
				return `${rootObjectOf(parent.callee)}.${callee}()`;
			}
			return undefined;
		}
		default:
			return undefined;
	}
}

/**
 * The problems in one file's source, on the given lines ('all' for every line).
 * @param {string} file
 * @param {string} source
 * @param {'all' | Set<number>} [lines]
 * @returns {Array<string>}
 */
export function lintSource(file, source, lines = 'all') {
	if (GENERATED_RE.test(source.slice(0, 500))) return [];
	let ast;
	try {
		ast = parse(source, {sourceType: 'module', plugins: ['typescript', 'jsx', 'decorators'], errorRecovery: true});
	} catch (error) {
		return [`${file}: could not parse: ${error.message}`];
	}
	const ignored = new Set();
	for (const comment of ast.comments ?? []) {
		if (IGNORE_RE.test(comment.value)) {
			ignored.add(comment.loc.end.line);
			ignored.add(comment.loc.end.line + 1);
		}
	}
	const problems = [];
	const ancestors = [];
	const visit = (node) => {
		if (!node || typeof node.type !== 'string') return;
		if (node.type === 'StringLiteral' || node.type === 'TemplateLiteral' || node.type === 'JSXText') {
			const parent = ancestors.at(-1);
			const nested = node.type !== 'JSXText' && parent?.type === 'TemplateLiteral';
			const text = textOf(node);
			const line = node.loc.start.line;
			if (
				!nested &&
				/\p{L}/u.test(text) &&
				(lines === 'all' || lines.has(line)) &&
				!ignored.has(line) &&
				!ignored.has(holderLine(ancestors, line))
			) {
				const sink = sinkOf(node, ancestors);
				const strict = sink?.startsWith('key ') || sink?.startsWith('variable ') || sink?.endsWith('()');
				if (sink && !(strict && !looksLikeProse(text)) && !isExcluded(ancestors)) {
					const shown = text.trim().replace(/\s+/g, ' ');
					problems.push(`${file}:${line}:${node.loc.start.column + 1}: ${sink}: ${JSON.stringify(shown)}`);
				}
			}
		}
		ancestors.push(node);
		for (const key of Object.keys(node)) {
			if (key === 'loc' || key === 'leadingComments' || key === 'trailingComments' || key === 'innerComments') continue;
			const value = node[key];
			if (Array.isArray(value)) value.forEach(visit);
			else if (value && typeof value === 'object' && typeof value.type === 'string') visit(value);
		}
		ancestors.pop();
	};
	visit(ast.program);
	return problems;
}

function optionValue(name, fallback) {
	const index = process.argv.indexOf(name);
	return index === -1 ? fallback : process.argv[index + 1];
}

function main() {
	const all = process.argv.includes('--all');
	const upstream = optionValue('--upstream', 'upstream/main');
	const given = process.argv.slice(2).filter((arg, i, args) => !arg.startsWith('--') && args[i - 1] !== '--upstream');
	let targets;
	if (all) {
		const files = given.length > 0 ? given : git('ls-files', '--', 'src').split('\n');
		targets = new Map(files.filter(Boolean).map((file) => [path.relative(APP_DIR, path.resolve(file)), 'all']));
	} else {
		const changes = forkChanges(upstream);
		targets = given.length > 0 ? new Map(given.map((file) => [file, changes.get(file) ?? new Set()])) : changes;
	}
	const problems = [];
	for (const [file, lines] of [...targets].sort(([a], [b]) => a.localeCompare(b))) {
		if (SOURCE_RE.test(file) && !SKIPPED_RE.test(file) && fs.existsSync(path.join(APP_DIR, file))) {
			problems.push(...lintSource(file, fs.readFileSync(path.join(APP_DIR, file), 'utf8'), lines));
		}
	}
	for (const problem of problems) console.log(problem);
	if (problems.length > 0) {
		console.error(
			`\n${problems.length} hard-coded user-facing string(s). Wrap each in msg/t/<Trans> and run ` +
				'`node scripts/fork-i18n.mjs sync`, or mark it `// i18n-ignore: <reason>`.',
		);
		process.exit(1);
	}
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
	main();
}
